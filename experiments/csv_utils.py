def get_error_message_content(error_msg_val, results_dir):
    """
    Given an error message value from CSV (which can be a relative file path under results_dir
    or a direct error string), returns the actual error text.
    """
    if not error_msg_val:
        return ""
    possible_path = os.path.join(results_dir, error_msg_val)
    if os.path.exists(possible_path) and os.path.isfile(possible_path):
        try:
            with open(possible_path, 'r', encoding='utf-8') as f:
                content = f.read().strip()
                if content:
                    return content
        except Exception:
            pass
    elif error_msg_val.startswith("error_msg/") or error_msg_val.startswith("raw_cex/"):
        return f"[Missing error log file: {error_msg_val}]"
    return error_msg_val.strip()

def get_error_histogram(csv_file, results_dir, target_status="ERROR_QUERY_EXECUTION"):
    """
    Reads a CSV file and returns a Counter of error messages for rows where EXTEST_STATUS == target_status.
    """
    from collections import Counter
    counts = Counter()
    if not os.path.exists(csv_file):
        return counts
    with open(csv_file, 'r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            if row.get("EXTEST_STATUS") == target_status:
                err_val = row.get("error_message", "")
                err_text = get_error_message_content(err_val, results_dir)
                if err_text:
                    err_clean = err_text.replace('\r\n', '\\n').replace('\n', '\\n')
                    counts[err_clean] += 1
                else:
                    counts["Unknown error (empty message)"] += 1
    return counts

