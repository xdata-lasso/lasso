def print_error_histogram(error_counts, title="ERROR_QUERY_EXECUTION Histogram", top_n=5):
    """
    Prints error histogram sorted from most frequent to least frequent.
    If top_n is specified, shows only top N. If top_n is None, shows all.
    """
    if not error_counts:
        return
    print(f"\n--- {title} ---")
    items = error_counts.most_common(top_n) if top_n is not None else error_counts.most_common()
    for err_msg, count in items:
        print(f"{count:5d}x | {err_msg}")

def format_status_counts(counter):
    """
    Formats a Counter of statuses into a concise single-line string
    suitable for tqdm.set_postfix_str without polluting terminal output.
    """
    if not counter:
        return ""
    priority_order = [
        ('NEQ', 'NEQ'),
        ('NEQ_SCO', 'SCO'),
        ('EXEC_EQ', 'EQ'),
        ('EQ_EXEC', 'EQ'),
        ('EQU', 'EQ'),
        ('EQ', 'EQ'),
        ('ERROR_QUERY_EXECUTION', 'ERR_EXEC'),
        ('TOOL_ERROR', 'TOOL_ERR'),
        ('TIMEOUT', 'TIMEOUT'),
        ('NO_DATASETS', 'NO_DS'),
        ('SKIPPED', 'SKIP'),
    ]
    parts = []
    seen = set()
    for key, label in priority_order:
        if counter.get(key, 0) > 0 and key not in seen:
            parts.append(f"{label}:{counter[key]}")
            seen.add(key)
    for key in sorted(counter.keys()):
        if key not in seen and counter[key] > 0:
            parts.append(f"{key}:{counter[key]}")
            seen.add(key)
    return " ".join(parts)

def print_status_update(pbar, counter, last_status=None):
    """
    Prints status counts on a new line using pbar.write() whenever counts change,
    keeping the main progress bar clean.
    """
    if last_status is None:
        last_status = [None]
    status_str = format_status_counts(counter)
    if status_str and status_str != last_status[0]:
        pbar.write(f"Statuses: {status_str}")
        last_status[0] = status_str

def is_completed_evaluation(row, results_dir=None, retry_eq=False):
    """
    Determines if a CSV result row represents a successfully completed evaluation
    that should be skipped during --retry.
    
    A row is considered complete if:
    1. (Unless retry_eq=True) Status represents equivalence ('EQ_EXEC', 'EXEC_EQ', 'EQ', 'EQU'),
       where no counterexample is expected.
    2. Status represents non-equivalence ('NEQ', 'NEQ_SCO'), AND a valid, non-empty counterexample file
       exists on disk (both reproducible_cex and raw_counterexample if present).
    Any other status (errors, timeouts, missing datasets, NEQ with missing/empty counterexample,
    or EQ/EQ_EXEC when retry_eq=True) is considered incomplete and should be retried.
    """
    if not row:
        return False
    status = (row.get('EXTEST_STATUS') or '').strip()
    raw_status = (row.get('raw_tool_status') or '').strip()
    if not retry_eq and (status in ('EQ_EXEC', 'EXEC_EQ', 'EQ', 'EQU') or raw_status in ('EQ', 'EQU', 'EQ_EXEC', 'EXEC_EQ')):
        return True
    if status in ('NEQ', 'NEQ_SCO'):
        cex_rel = (row.get('reproducible_cex') or '').strip()
        if not cex_rel:
            return False
        cex_path = os.path.join(results_dir, cex_rel) if results_dir else cex_rel
        if not (os.path.exists(cex_path) and os.path.isfile(cex_path) and os.path.getsize(cex_path) > 0):
            return False
            
        raw_cex_rel = (row.get('raw_counterexample') or '').strip()
        if raw_cex_rel:
            raw_path = os.path.join(results_dir, raw_cex_rel) if results_dir else raw_cex_rel
            if not (os.path.exists(raw_path) and os.path.isfile(raw_path) and os.path.getsize(raw_path) > 0):
                return False
                
        return True
    return False

def load_existing_results(csv_path):
    """
    Reads an existing results CSV and returns a dictionary of {(instance_id, prediction_id): row},
    keeping the latest row in case of duplicate entries.
    """
    if not os.path.exists(csv_path) or os.path.getsize(csv_path) == 0:
        return {}
    try:
        with open(csv_path, 'r', encoding='utf-8') as f:
            reader = csv.DictReader(f)
            return {(str(row['instance_id']).strip(), str(row['prediction_id']).strip()): row 
                    for row in reader if 'instance_id' in row and 'prediction_id' in row}
    except Exception as e:
        print(f"Warning: Could not read {csv_path}: {e}")
        return {}

def filter_predictions_for_evaluation(data, results_dir, csv_file_func, resume=False, retry=False, target_instance_id=None, target_prediction_id=None, tool_name="Tool", retry_eq=False):
    """
    Cross-checks all predictions in `data` (from queries.json) against existing results CSVs.
    
    Parameters:
        data: list of items loaded from queries.json
        results_dir: path to results directory
        csv_file_func: callable taking `src` and returning the CSV file path for that source
        resume: boolean flag
        retry: boolean flag
        target_instance_id: optional filter for a specific instance
        target_prediction_id: optional filter for a specific prediction
        tool_name: display name for logging
        retry_eq: if True during retry, also retries queries marked as EQ / EQ_EXEC / EXEC_EQ / EQU
        
    Returns:
        (filtered_data, total_predictions_to_run)
    """
    from collections import defaultdict
    unique_sources = set(item.get('source', 'unknown') for item in data)
    existing_by_source = {}
    if resume or retry:
        for src in unique_sources:
            out_csv = csv_file_func(src)
            existing_by_source[src] = load_existing_results(out_csv)

    stats = defaultdict(lambda: {'total': 0, 'completed': 0, 'retry': 0, 'missing': 0, 'to_run': 0})
    filtered_data = []

    for item in data:
        src = item.get('source', 'unknown')
        db_id = item.get('schema_id', item.get('database_id'))
        instance_id = str(item.get('id') or item.get('instance_id') or db_id).strip()

        if target_instance_id and instance_id != str(target_instance_id).strip():
            continue

        existing_rows = existing_by_source.get(src, {})
        remaining_preds = []

        for idx, pred in enumerate(item.get('predictions', [])):
            pred_id = str(pred.get('prediction_id') or f"pred_{idx}").strip()
            if target_prediction_id and pred_id != str(target_prediction_id).strip():
                continue

            stats[src]['total'] += 1
            pair = (instance_id, pred_id)

            if retry:
                if pair in existing_rows and is_completed_evaluation(existing_rows[pair], results_dir, retry_eq=retry_eq):
                    stats[src]['completed'] += 1
                else:
                    if pair in existing_rows:
                        stats[src]['retry'] += 1
                    else:
                        stats[src]['missing'] += 1
                    remaining_preds.append(pred)
            elif resume:
                if pair in existing_rows:
                    stats[src]['completed'] += 1
                else:
                    stats[src]['missing'] += 1
                    remaining_preds.append(pred)
            else:
                remaining_preds.append(pred)

        if remaining_preds:
            item_copy = item.copy()
            item_copy['predictions'] = remaining_preds
            filtered_data.append(item_copy)

    total_predictions = sum(len(item.get('predictions', [])) for item in filtered_data)

    if resume or retry:
        retry_label = "unrefuted/EQ/failed (to retry)" if retry_eq else "failed/missing-CEX (to retry)"
        for src in sorted(unique_sources):
            st = stats[src]
            st['to_run'] = st['retry'] + st['missing'] if retry else st['missing']
            mode_desc = "Retry" if retry else "Resume"
            print(f"[{tool_name} {mode_desc}] Cross-checked '{src}' against queries.json: "
                  f"{st['total']} total | {st['completed']} completed (skipped) | "
                  f"{st['retry']} {retry_label} | "
                  f"{st['missing']} missing from CSV (to evaluate) => {st['to_run']} to run")

    return filtered_data, total_predictions

