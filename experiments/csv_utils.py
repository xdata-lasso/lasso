import csv
import os

def get_results_dir(base_dir: str, dialect: str = None) -> str:
    """
    Returns the dialect-specific results directory:
    - postgresql / postgres -> <base_dir>/results/postgresql
    - mysql -> <base_dir>/results/mysql
    - sqlite / native / default -> <base_dir>/results
    """
    if not dialect or dialect in ('native', 'sqlite', 'sqlite3', ''):
        return os.path.join(base_dir, 'results')
    d = str(dialect).lower().strip()
    if d in ('postgres', 'postgresql'):
        sub = 'postgresql'
    elif d == 'mysql':
        sub = 'mysql'
    else:
        sub = d
    return os.path.join(base_dir, 'results', sub)

def update_or_append_results(csv_path, fieldnames, new_results):
    """
    Appends new results to the CSV file. 
    To remove any duplicates generated by retries, call deduplicate_csv at the end of the script.
    """
    file_exists = os.path.exists(csv_path) and os.path.getsize(csv_path) > 0
    with open(csv_path, 'a', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        if not file_exists:
            writer.writeheader()
        writer.writerows(new_results)

def deduplicate_csv(csv_path, fieldnames=None, valid_query_pairs=None):
    """
    Reads the entire CSV, deduplicates by (instance_id, prediction_id) keeping the latest,
    filters to keep only query pairs present in valid_query_pairs (if provided),
    and rewrites the CSV if duplicates or orphaned rows exist.
    If fieldnames is None, preserves the original header.
    Returns (num_duplicates, num_orphaned).
    """
    if not os.path.exists(csv_path) or os.path.getsize(csv_path) == 0:
        return 0, 0
        
    with open(csv_path, 'r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        actual_fieldnames = fieldnames or reader.fieldnames
        existing_rows = list(reader)
        
    if not existing_rows or not actual_fieldnames:
        return 0, 0
        
    row_dict = {}
    valid_rows_count = 0
    orphaned_count = 0
    for row in existing_rows:
        inst_id = str(row.get('instance_id', '')).strip()
        pred_id = str(row.get('prediction_id', '')).strip()
        if inst_id and pred_id:
            if valid_query_pairs is not None and (inst_id, pred_id) not in valid_query_pairs:
                orphaned_count += 1
                continue
            row_dict[(inst_id, pred_id)] = row
            valid_rows_count += 1
            
    num_duplicates = valid_rows_count - len(row_dict)
    if num_duplicates > 0 or orphaned_count > 0 or len(row_dict) < len(existing_rows):
        with open(csv_path, 'w', newline='', encoding='utf-8') as f:
            writer = csv.DictWriter(f, fieldnames=actual_fieldnames)
            writer.writeheader()
            writer.writerows(row_dict.values())
            
    return num_duplicates, orphaned_count

