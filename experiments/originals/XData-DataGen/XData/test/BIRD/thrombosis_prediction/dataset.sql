CREATE TABLE patient (
    id integer NOT NULL,
    sex varchar,
    birthday date,
    descrip date,
    First_Date date,
    admission varchar,
    diagnosis varchar,
    PRIMARY KEY (id)
);
CREATE TABLE examination (
    id integer,
    Examination_Date date,
    aCLIgG real,
    aCLIgM real,
    ana integer,
    ANAPattern varchar,
    aCLIgA integer,
    diagnosis varchar,
    kct varchar,
    rvvt varchar,
    lac varchar,
    symptoms varchar,
    thrombosis integer,
    FOREIGN KEY (id) REFERENCES patient (id)
);
