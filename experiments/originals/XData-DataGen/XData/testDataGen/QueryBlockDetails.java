	public static String defineWindowMap(GenerateCVC1 cvc, QueryBlockDetails qb, Vector<String> sqTableListNames,String joinTable) throws Exception
	{
		String tempConstraints="";

		HashMap<String, Vector<Column> > forMap = new HashMap<>();

		getColumnsForMapping(cvc,qb, forMap);

		int c=0;
		
		for(String joinTablesLR: sqTableListNames)
		{
			//joinTablesLR="JSQ1";
			int joincol = 0;

			String fun = ("define-fun " + joinTable + "_map_" + joinTablesLR+ "((x!0 " + "Int" + ") (x!1 "
					+ "Int" + ")) Bool\n");

			tempConstraints += "\n(" + fun + "(and \n";
			int col1 = 0;

			while (col1 < forMap.get(joinTablesLR).size()) {
				
				int index = cvc.getTableMap().getSQTableByName(joinTablesLR).getColumnIndex(forMap.get(joinTablesLR).get(col1).getColumnName());

				Expr left = ConstraintGenerator.genSelectTest2(cvc, joinTablesLR,
						index , "x!0");
				
				Expr right = null;
				if(forMap.get(joinTablesLR).get(col1).getColumnName().contains("XDATA_CNT")==false)
				{
					right = ConstraintGenerator.genSelectTest2(cvc, joinTable, joincol, "x!1");
				}
				else
				{
					int lastColIndex = cvc.getTableMap().getSQTableByName(joinTable).getNoOfColumn() -1;
					right = ConstraintGenerator.genSelectTest2(cvc, joinTable, lastColIndex, "x!1");

				}
				Expr eq = ConstraintGenerator.ctx.mkEq(left, right);
				tempConstraints += eq.toString() + "\n";
				col1++;
				joincol++;
			}
			c+=1;
			tempConstraints += ")\n)\n";

		}

		return tempConstraints;
	}

