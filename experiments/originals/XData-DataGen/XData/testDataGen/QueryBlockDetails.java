			col.setTableName(joinTable);
			col.setTable(sqi);
			col.setBaseRelation(tables.get(0).getTableName());
			col.isProjected =1;
			sqi.addColumn(col);

			if (flag == 1)
				sqi.addColumnInPrimaryKey(col);
			

