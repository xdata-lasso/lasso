					IntExpr zero = ConstraintGenerator.ctx.mkInt(0), one = ConstraintGenerator.ctx.mkInt(1);
					// condition: (> cntExprL 0) and (= cntExprR 0)
					BoolExpr cond = ConstraintGenerator.ctx.mkAnd(
						ConstraintGenerator.ctx.mkGt((ArithExpr) cntExprL, zero),
						ConstraintGenerator.ctx.mkEq(cntExprR, zero)
					);
					// finalCnt = (ite cond 1 0)
