	public static void transformNodes(GenerateCVC1 context, QueryBlockDetails queryBlock) {
		for (Node node : queryBlock.getProjectedCols()) {
			
			// 1. Handle WITH clause alias mapping and SubQuery transformations
			if (context.aliasMappingToLevelsForWith != null && node != null) {
				String tableName = node.getTableNameNo().toLowerCase();
				String baseTableName = tableName.replaceAll("\\d+$", "");

				if (context.aliasMappingToLevelsForWith.containsKey(baseTableName)) {
					// Get replacement SubQuery table info
					String baseTableFullTrim = tableName.replaceAll("\\d+$", "");
					String replacementSQTableName = context.aliasMappingToLevelsForWith.get(baseTableFullTrim).repSQTable;
					
					int colIndex = node.getTable().getColumnIndex(node.getColumn().toString());
					Table replacementTable = context.getTableMap().getSQTableByName(replacementSQTableName);
					
					// Extract column name by removing prefix before "__"
					String fullColumnName = replacementTable.getColumn(colIndex).toString();
					String targetColumnName = fullColumnName.split("__")[1].replaceAll("\\d+$", "");

					// Map to the Joint SubQuery 0 (JSQ0)
					String targetSQAlias = "JSQ0";
					Table jsq0Table = context.getTableMap().getSQTableByName(targetSQAlias);

					for (String jsq0ColumnKey : jsq0Table.getColumns().keySet()) {
						if(!jsq0ColumnKey.contains("__")) continue;
						String cleanJsq0ColumnName = jsq0ColumnKey.split("__")[1].replaceAll("\\d+$", "");
						
						if (cleanJsq0ColumnName.equalsIgnoreCase(targetColumnName)) {
							node.setColumn(jsq0Table.getColumn(jsq0ColumnKey));
							break;
						}
					}

					node.setTable(jsq0Table);
					node.setTableAlias(replacementSQTableName);
					node.setTableNameNo(targetSQAlias);
				}
			}

			// 2. Synchronize Aggregate expression details with the parent Node
			if (node.getAgg() != null) {
				Node aggExpression = node.getAgg().getAggExp();
				
				if (aggExpression.getTable() != node.getTable()) {
					aggExpression.setTable(node.getTable());
					aggExpression.setTableAlias(node.getTableAlias());
					aggExpression.setTableNameNo(node.getTableNameNo());
					aggExpression.setColumn(node.getColumn());
				}
			}
		}
	}
	/**
	 * This method is used to get constraints for where clause subquery components
	 * 
	 * @author Sunanda
	 * @param qb
	 * @param cvc
	 * @return constraints
	 */
	private static String addWhereClauseSubqueryRelatedConstraints(GenerateCVC1 cvc, QueryBlockDetails qb)
        throws Exception {
    String constraintString = "";

    for (QueryBlockDetails qbt : qb.getWhereClauseSubQueries()) {
		GenerateJoinPredicateConstraints.fixBaseRelations(cvc, qbt);
        // If distinct and aggregation present, push projected columns into group by
        if (qbt.isDistinct && isAggregationPresentInQuery(qbt)) {
            pushProjectedColumnsInGroupBy(qbt.getProjectedCols(), qbt.getGroupByNodes());
        }

        String temp = "where_" + qbt.getLevel();

        // Add subquery constraint definitions and correlation constraints
        if (cvc.subqueryConstraintsMap.size() > 0 &&
            cvc.subqueryConstraintsMap.containsKey(temp) &&
            !cvc.subqueryConstraintsMap.get(temp).SQDefine.isEmpty()) {

            String constr = "";
            for (String joinTable : cvc.subqueryConstraintsMap.get(temp).SQDefine.keySet()) {
                Vector<Node> correlationConds = cvc.subqueryConstraintsMap.get(temp).SQJoinCorrelationConds.get(joinTable);
                constr += cvc.subqueryConstraintsMap.get(temp).SQDefine.get(joinTable);

                if (Configuration.outerSQ.equalsIgnoreCase("false")) {
                    constr += GenerateJoinPredicateConstraints.generateConstraintsForCorrelationAttributes(
                        cvc, joinTable, correlationConds, qbt.getLevel()) + "\n";
                }
            }
            constraintString += constr;
        }

        constraintString += ConstraintGenerator.addCommentLine("END OF CONSTRAINTS FOR WHERE CLAUSE SUBQUERY: JOIN SUBQUERY TABLE ");

        if (!qbt.isDistinct && isAggregationPresentInQuery(qbt)) {
            if (qbt.getHavingClause() != null) {
                pushHavingClauseAttrInProjectedColumns(qbt.getHavingClause(), qbt.getProjectedCols());
            }

            for (Node n : cvc.correlationHashMap.keySet()) {
                Node k = cvc.correlationHashMap.get(n).getCondition();
                if (n.getLevel() == qbt.getLevel()) {
                    if (cvc.correlationHashMap.get(n).getOriginalLevelLeft() == qbt.getLevel())
                        pushGrpbyAttrInProjectedColumns(k.getLeft(), qbt);
                    if (cvc.correlationHashMap.get(n).getOriginalLevelRight() == qbt.getLevel())
                        pushGrpbyAttrInProjectedColumns(k.getRight(), qbt);
                }
            }

            if (Configuration.getProperty("cntFlag").equalsIgnoreCase("false")) {
                constraintString += ConstraintGenerator.GetGroupByConstraintsForSubqueryTableWithoutCount(cvc, qbt, temp);
            } else {
                constraintString += ConstraintGenerator.GetGroupByConstraintsForSubqueryTableWithCount(cvc, qbt, temp, "");
            }

        } else if (qbt.isDistinct) {
            pushProjectedColumnsInGroupBy(qbt.getProjectedCols(), qbt.getGroupByNodes());

            // Here passing 5 arguments: you can adjust depending on your ConstraintGenerator method signature
            constraintString += ConstraintGenerator.GetDistinctClauseConstraintsForSubqueryTableWithCount(cvc, qbt, temp, "DSQ", 0);

            removeProjectedColumnsFromGroupBy(qbt.getProjectedCols(), qbt.getGroupByNodes());

        } else {
            // Handle non-distinct, non-aggregation case (from first function)
            pushProjectedColumnsInGroupBy(qbt.getProjectedCols(), qbt.getGroupByNodes());

            Node prNode = qbt.getProjectedCols().get(0);
            Column c = prNode.getColumn();

            Node aggNode = prNode.clone();
            AggregateFunction ag = new AggregateFunction();
            Node columnNode = new Node(aggNode);
            ag.setAggExp(columnNode);
            ag.setFunc(AggregateFunction.getAggCOUNT());
            aggNode.setOrgiColumn(c);
            aggNode.setAgg(ag);
            aggNode.setType(Node.getAggrNodeType());
            aggNode.setTableNameNo(columnNode.getTableNameNo());
            aggNode.setIsMutant(true);

            qbt.getProjectedCols().add(aggNode);

            // constraintString += ConstraintGenerator.GetDistinctClauseConstraintsForSubqueryTableWithCount(cvc, qbt, temp, "DSQ", 1);

            removeProjectedColumnsFromGroupBy(qbt.getProjectedCols(), qbt.getGroupByNodes());
            qbt.getProjectedCols().remove(aggNode);
        }

        constraintString += ConstraintGenerator.addCommentLine(" END OF WHERE CLAUSE SUBQUERY BLOCK ");
    }

    return constraintString;
}


