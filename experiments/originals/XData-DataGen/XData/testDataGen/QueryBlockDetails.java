				// 2. Logic: if (L > R) then (L - R) else (R - L)
				BoolExpr q1GtQ2 = ConstraintGenerator.ctx.mkGt((ArithExpr)cntExprL, (ArithExpr)cntExprR);
				ArithExpr subLminusR = ConstraintGenerator.ctx.mkSub((ArithExpr)cntExprL, (ArithExpr)cntExprR);
				ArithExpr subRminusL = ConstraintGenerator.ctx.mkSub((ArithExpr)cntExprR, (ArithExpr)cntExprL);

				// One single ITE is enough
				Expr finalIteLogic = ConstraintGenerator.ctx.mkITE(q1GtQ2, subLminusR, subRminusL);

