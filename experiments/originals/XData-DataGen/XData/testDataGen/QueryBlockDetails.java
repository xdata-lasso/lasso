	public static String getTuplesEqualConstraints(GenerateCVC1 cvc, String leftTable, String rightTable, Vector<Column> leftCol, Vector<Column> rightCol) {
		Context ctx = ConstraintGenerator.ctx;
		// Compare each projected column and the count column for equality
		BoolExpr[] equalities = new BoolExpr[leftCol.size()];
		for (int k = 0; k < leftCol.size(); k++) {
			int idx = cvc.getTableMap().getSQTableByName(leftTable).getColumnIndex(leftCol.get(k).toString());
			Expr leftVal = ConstraintGenerator.genSelectTest2(cvc, leftTable, idx, "i");
			idx = cvc.getTableMap().getSQTableByName(rightTable).getColumnIndex(rightCol.get(k).toString());
			Expr rightVal = ConstraintGenerator.genSelectTest2(cvc, rightTable, idx, "j");
			
			// Handle type mismatch between Integer and Real sorts using to_real (mkInt2Real)
			if (leftVal.getSort().equals(ctx.getIntSort()) && rightVal.getSort().equals(ctx.getRealSort())) {
				leftVal = ctx.mkInt2Real((com.microsoft.z3.IntExpr) leftVal);
			} else if (leftVal.getSort().equals(ctx.getRealSort()) && rightVal.getSort().equals(ctx.getIntSort())) {
				rightVal = ctx.mkInt2Real((com.microsoft.z3.IntExpr) rightVal);
			}

			try {
				equalities[k] = ctx.mkEq(leftVal, rightVal);
			} catch (com.microsoft.z3.Z3Exception e) {
				cvc.incompatible=true;
				return "";
			}
		}

		BoolExpr tuplesEqualBody = ctx.mkAnd(equalities);

		return "(define-fun tuples_equal ((i Int) (j Int)) Bool\n  " + 
			tuplesEqualBody.toString() + "\n)\n";
	}

	/**
	 * Creates the inner constraint for the 'j' loop. 
	 * If unroll is true, returns an AND of all possible values. 
	 * If unroll is false, returns a forall quantifier.
	 */
	private static BoolExpr getInnerConstraint(GenerateCVC1 cvc,Context ctx,Expr i,int innerSize,String innerTable,int innerCountIdx,FuncDecl tuplesEqualDecl,Boolean unroll,Boolean isLeftToRight){
		if(unroll){
			BoolExpr[] conjuncts=new BoolExpr[innerSize];
			for(int k=1;k<=innerSize;k++){
				Expr concreteJ= ctx.mkInt(k);
				Expr arg1= isLeftToRight?i:concreteJ;
				Expr arg2 = isLeftToRight ? concreteJ:i;
				conjuncts[k-1]=ctx.mkImplies(ctx.mkGt((ArithExpr) ConstraintGenerator.genSelectTest(cvc, innerTable, innerCountIdx, k), ctx.mkInt(0)),ctx.mkNot((BoolExpr) tuplesEqualDecl.apply(arg1, arg2))
            );
			}
			return ctx.mkAnd(conjuncts);
		}else{
			Expr j = ctx.mkIntConst("j");
			Expr arg1 = isLeftToRight ? i : j;
			Expr arg2 = isLeftToRight ? j : i;
			
			return (BoolExpr) ctx.mkForall(new Expr[]{j}, 
				ctx.mkImplies(
					ctx.mkAnd(
						ctx.mkGe((ArithExpr)j, ctx.mkInt(1)), 
						ctx.mkLe((ArithExpr)j, ctx.mkInt(innerSize)),
						ctx.mkGt((ArithExpr)ConstraintGenerator.genSelectTest2(cvc, innerTable, innerCountIdx, "j"), ctx.mkInt(0))
					),
					ctx.mkNot((BoolExpr)tuplesEqualDecl.apply(arg1, arg2))
				), 1, null, null, null, null);

		}
	}
