	public static Boolean isAggregationPresentInQuery(QueryBlockDetails qbt) {

		if (qbt.groupByNodes.size() != 0)
			return true;
		for (Node prjColumn : qbt.getProjectedCols()) {
			if (prjColumn.getType().equalsIgnoreCase("AGGREGATE NODE") 
				&& !prjColumn.fromBelowLevelFClauseSQ
				&& qbt.getBaseRelations().contains(
					prjColumn.getTableAlias()!=null && !prjColumn.getTableAlias().equalsIgnoreCase("") ? 
						prjColumn.getTableAlias().toUpperCase() : prjColumn.getTableNameNo().toUpperCase()) )
				return true;
			if (prjColumn.getType().equalsIgnoreCase("AGGREGATE NODE") 
				&& !prjColumn.fromBelowLevelFClauseSQ
				&& qbt.getBaseSQRelations().contains(
					prjColumn.getTableAlias()!=null && !prjColumn.getTableAlias().equalsIgnoreCase("") ? 
						prjColumn.getTableAlias().toUpperCase() : prjColumn.getTableNameNo().toUpperCase()) )
				return true;
		}
		return false;
	}

