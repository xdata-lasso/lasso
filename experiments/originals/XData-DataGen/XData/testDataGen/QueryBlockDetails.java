	public static Vector<Column> getColumnsFromQueryBlock(GenerateCVC1 cvc,QueryBlockDetails qb){
		Vector<Column>tableColumns= new Vector<>();
		ArrayList<Node> projectedColNodes = qb.getProjectedCols();
		String tableName=qb.baseSQ;
		int size = cvc.getTableMap().getSQTables().get(tableName).getNoOfColumn();
		for(Node x:projectedColNodes){
			String getColName ;
			String getTabName;
			if(x.getNodeType().equals(Node.getCaseNodeType())){
				getColName="__EXP";
				for(int i=0 ; i<size ; i++){
					Column col=cvc.getTableMap().getSQTableByName(tableName).getColumn(i);
					String currColString = col.getColumnName(),colString=col.getColumnName();
					if(currColString.contains(getColName)){	
						tableColumns.add(cvc.getTableMap().getSQTableByName(tableName).getColumn(i));
						break; 
					}
					
				}
			}else{
				getColName = (x.getOriginalCol()==null ? (x.orderNodesInWindow.size()>0 ? x.orderNodesInWindow.get(0).getOriginalCol().getColumnName() : "" ): x.getOriginalCol().getColumnName() );
				if(getColName.length()==0) getColName=x.getColumn().toString();
				getTabName=x.getTable().toString();
				for(int i=0 ; i<size ; i++){
					Column col=cvc.getTableMap().getSQTableByName(tableName).getColumn(i);
					String currColString = col.getColumnName(),colString=col.getColumnName();
					if(currColString.contains("__")) currColString=currColString.split("__")[1].replaceAll("\\d", "");
					if(currColString.equalsIgnoreCase(getColName)  && x.getAgg()==null && colString.contains(getTabName) )
						{	tableColumns.add(cvc.getTableMap().getSQTableByName(tableName).getColumn(i));
							break; 
						}
					if(currColString.equalsIgnoreCase(getColName) && x.getAgg()!=null && colString.contains(x.getAgg().getFunc()) )
						{	tableColumns.add(cvc.getTableMap().getSQTableByName(tableName).getColumn(i));
							break; 
						}
				}
			}
				
		}
		tableColumns.add(cvc.getTableMap().getSQTableByName(tableName).getColumn(size-1));
		return tableColumns;
	}
