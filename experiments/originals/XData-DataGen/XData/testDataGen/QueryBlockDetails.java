	private static HashMap<String, Object> createTempSetTables(GenerateCVC1 cvc, String joinTable, 
	Vector<Table> tables, String sqType, QueryBlockDetails qbl, QueryBlockDetails qbr ) throws Exception {
		
		HashMap<String, Object> columnNameAndDataTypes = new HashMap<String, Object>();
		ArrayList<String> columns = new ArrayList<String>();
		ArrayList<Sort> columnDataTypes = new ArrayList<Sort>();
		ArrayList<String> primaryKey = new ArrayList<String>();
		String columnName = "";
		Table sqi = new Table(joinTable);
		Map<String, Table> tableMap = new HashMap<String, Table>();
		Vector<String> countColumnsOfBaseTables = new Vector<String>();

		ArrayList<Node> projectedColNodes =qbl.getProjectedCols();	

		int index=0;

		for(Node x : projectedColNodes)
		{
			columnName = joinTable + "_" + x.getColumn().getColumnName() + String.valueOf(index);

			columns.add(columnName);
			//INFO:Need to add more according to type
			if(x.getNodeType().equals(Node.getAggrNodeType()) && x.getAgg() != null && (x.getAgg().getFunc().equals("COUNT") || x.getAgg().getFunc().equals("AVG") || x.getAgg().getFunc().equals("SUM")))
				columnDataTypes.add(ConstraintGenerator.ctx.getIntSort());
			else
				columnDataTypes.add(ConstraintGenerator.getColumnSort(x.getColumn().getCvcDatatype()));
			int flag = 0;

			Table curr = null;

			for(int i=0 ; i<tables.size() ; i++)
			{
				if(tables.get(i).getTableName().equalsIgnoreCase(qbl.baseSQ))
				{
					curr=tables.get(i);
					break;
				}
			}

			if (checkPrimary(curr.getPrimaryKey(), x.getColumn())) {
				primaryKey.add(columnName);
				flag = 1;
			}
			Column col = new Column(x.getColumn());
			if(x.getNodeType().equals(Node.getAggrNodeType()) && (x.getAgg().getFunc().equals("COUNT") || x.getAgg().getFunc().equals("AVG") || x.getAgg().getFunc().equals("SUM"))){
				col.setCvcDatatype("INT");
				col.setColumnValues(null);
			}
			col.setColumnName(columnName);
			col.setTableName(joinTable);
			col.setTable(sqi);
			col.setBaseRelation(tables.get(0).getTableName());
			col.isProjected =1;
			sqi.addColumn(col);

			if (flag == 1)
				sqi.addColumnInPrimaryKey(col);
			

			index++;
		}

		if (Configuration.getProperty("cntFlag").equalsIgnoreCase("true")) {
			columns.add(joinTable+"_"+qbl.baseSQ + "__XDATA_CNT" + String.valueOf(index));
			columnDataTypes.add(ConstraintGenerator.ctx.getIntSort());
			Column col = new Column(joinTable+"_"+qbl.baseSQ + "__XDATA_CNT" + String.valueOf(index), sqi);
			col.ltakes=1;
			col.setDataType(4);// INT
			col.setCvcDatatype("INT");
			col.setColumnSize(0);
			sqi.addColumn(col);
			countColumnsOfBaseTables.add(joinTable+"_"+qbl.baseSQ + "__XDATA_CNT" + String.valueOf(index));
			index++;
		}

		if (Configuration.getProperty("cntFlag").equalsIgnoreCase("true")) {
			
			columns.add(joinTable+"_"+qbr.baseSQ + "__XDATA_CNT" + String.valueOf(index));
			columnDataTypes.add(ConstraintGenerator.ctx.getIntSort());
			Column col = new Column(joinTable+"_"+qbr.baseSQ + "__XDATA_CNT" + String.valueOf(index), sqi);
			col.rtakes=1;
			col.setDataType(4);// INT
			col.setCvcDatatype("INT");
			col.setColumnSize(0);
			sqi.addColumn(col);
			countColumnsOfBaseTables.add(joinTable+"_"+qbr.baseSQ + "__XDATA_CNT" + String.valueOf(index));
			index++;
		}

		
		if (Configuration.getProperty("cntFlag").equalsIgnoreCase("true")) {
			columns.add(joinTable + "__XDATA_CNT");
			columnDataTypes.add(ConstraintGenerator.ctx.getIntSort());
			Column col = new Column(joinTable + "__XDATA_CNT", sqi);
			col.takes=1;
			col.setDataType(4);// INT
			col.setCvcDatatype("INT");
			col.setColumnSize(0);
			sqi.addColumn(col);
			countColumnsOfBaseTables.add(joinTable + "__XDATA_CNT");
		}

		sqi.setSQType(sqType);
		tableMap.put(joinTable, sqi);
		columnNameAndDataTypes.put("Names", columns);
		columnNameAndDataTypes.put("DataTypes", columnDataTypes);
		columnNameAndDataTypes.put("PrimaryKey", primaryKey);
		columnNameAndDataTypes.put("TableMap", tableMap);
		columnNameAndDataTypes.put("CountColumns", countColumnsOfBaseTables);
		cvc.getTableMap().putSQTables(tableMap);
		return columnNameAndDataTypes;
	}

