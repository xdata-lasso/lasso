	public static String getEquivalenceConstraints(GenerateCVC1 cvc,QueryBlockDetails qb,QueryBlockDetails qbl,QueryBlockDetails qbr) throws Exception{
		Context ctx= ConstraintGenerator.ctx;
		Vector<Column>leftCol=getColumnsFromQueryBlock(cvc, qbl);
		Vector<Column>rightCol=getColumnsFromQueryBlock(cvc, qbr);
		Boolean unrollExists=true;
		
		String leftTable=qbl.baseSQ,rightTable=qbr.baseSQ;
		int leftSize=cvc.getNoOfTuples().get(leftTable),rightSize=cvc.getNoOfTuples().get(rightTable)  ;
		if(leftCol.size()!=rightCol.size()){
			cvc.incompatible=true;
			return getConstraintsForCntGreaterThanZero(cvc, cvc.getTableMap().getSQTableByName(leftTable), leftSize);
		}
		// Generate the define-fun for tuple comparison
		String tuplesEqualDef=getTuplesEqualConstraints(cvc, leftTable, rightTable, leftCol, rightCol);
		if(tuplesEqualDef.length()==0) return getConstraintsForCntGreaterThanZero(cvc, cvc.getTableMap().getSQTableByName(leftTable), leftSize);
		//Building the non-equivalence assertion
		Expr i= ctx.mkIntConst("i"),j=ctx.mkIntConst("j");
		int countColIndex= leftCol.size()-1;
		int countColIndexLeft=cvc.getTableMap().getSQTableByName(leftTable).getColumnIndex(leftCol.get(countColIndex).toString()),countColIndexRight=cvc.getTableMap().getSQTableByName(rightTable).getColumnIndex(rightCol.get(countColIndex).toString());

		// Define the function handle to refer to 'tuples_equal' in quantification
		FuncDecl tuplesEqualDecl = ctx.mkFuncDecl("tuples_equal", new Sort[]{ctx.getIntSort(),ctx.getIntSort()}, ctx.getBoolSort());
		BoolExpr innerForLeft = getInnerConstraint(cvc, ctx, i, rightSize, rightTable, countColIndexRight, tuplesEqualDecl, unrollExists, true);
		//There is a i in left which is not present in right
		BoolExpr existsInLeftMissingInRight = (BoolExpr) ctx.mkExists(new Expr[]{i}, 
        ctx.mkAnd(
            ctx.mkGe((ArithExpr)i, ctx.mkInt(1)), 
            ctx.mkLe((ArithExpr)i, ctx.mkInt(leftSize)),
            ctx.mkGt((ArithExpr)ConstraintGenerator.genSelectTest2(cvc, leftTable, countColIndexLeft, "i"), ctx.mkInt(0)),innerForLeft
        ), 1, null, null, null, null);
		BoolExpr innerForRight = getInnerConstraint(cvc, ctx, i, leftSize, leftTable, countColIndexLeft, tuplesEqualDecl, unrollExists, false);
		//There exist a j in right which is not present in left
		BoolExpr existsInRightMissingInLeft = (BoolExpr) ctx.mkExists(new Expr[]{i}, 
        ctx.mkAnd(
            ctx.mkGe((ArithExpr)i, ctx.mkInt(1)), 
            ctx.mkLe((ArithExpr)i, ctx.mkInt(rightSize)),
            ctx.mkGt((ArithExpr)ConstraintGenerator.genSelectTest2(cvc, rightTable, countColIndexRight, "i"), ctx.mkInt(0)),innerForRight
        ), 1, null, null, null, null);

		ArithExpr[] leftCounts = new ArithExpr[leftSize];
		for (int k = 1; k <= leftSize; k++) {
			leftCounts[k - 1] = (ArithExpr) ConstraintGenerator.genSelectTest(cvc, leftTable, countColIndexLeft, k);
		}
		ArithExpr leftSum = ctx.mkAdd(leftCounts);

		// Build Right Sum
		ArithExpr[] rightCounts = new ArithExpr[rightSize];
		for (int k = 1; k <= rightSize; k++) {
			rightCounts[k - 1] = (ArithExpr) ConstraintGenerator.genSelectTest(cvc, rightTable, countColIndexRight, k);
		}
		ArithExpr rightSum = ctx.mkAdd(rightCounts);

		// BoolExpr a3: sum_left != sum_right
		BoolExpr sumsNotEqual = ctx.mkNot(ctx.mkEq(leftSum, rightSum));

		// Combine all three conditions in an OR
		String assertStr = "(assert\n" + ctx.mkOr(existsInLeftMissingInRight, existsInRightMissingInLeft, sumsNotEqual).toString() + "\n)";
		return tuplesEqualDef+assertStr;


	}
	public static String queryBlockHelper(GenerateCVC1 cvc, QueryBlockDetails qb) throws Exception
	{
		String constraintString = "";

		if(qb.getLeftBlockDetails().isSet==-1 )
		{
			constraintString+= TraverseNestedQueryBlock(cvc,qb.getLeftBlockDetails());
		}
		if(qb.getRightBlockDetails().isSet==-1 )
		{
			constraintString+= TraverseNestedQueryBlock(cvc,qb.getRightBlockDetails());
		}

		if(qb.getLeftBlockDetails().isSet==1)
		{
			constraintString+= queryBlockHelper(cvc, qb.getLeftBlockDetails());
		}

		if(qb.getRightBlockDetails().isSet==1)
		{
			constraintString+= queryBlockHelper(cvc, qb.getRightBlockDetails());
		}
		
		if(qb.baseSQ.contains("SETOP") )
		{
			if(Configuration.getProperty("setOpResultTable").equalsIgnoreCase("true")){
				constraintString += getConstraintsForSet(cvc, qb.leftBlock,qb.rightBlock, qb.setOperatorString, qb.getLevel());
				constraintString += getXDATACNTForSet(cvc,qb.setOperatorString, qb.isAll, "SETOP"+String.valueOf(qb.getLevel())  );

				if(cvc.getTypeOfMutation().equalsIgnoreCase("DATASET FOR GENERATING NON EMPTY RESULT "))
				{
					constraintString += moreThanZeroTuple(cvc,"SETOP"+String.valueOf(qb.getLevel()));
				}
				else if(cvc.getTypeOfMutation().equalsIgnoreCase("DATASET TO KILL SET OPERATOR MUTATIONS "))
				{
					if(cvc.oneOrZero==1)
					{
						constraintString += moreThanOneTuple(cvc,"SETOP"+String.valueOf(qb.getLevel()));
					}
					else
					{
						constraintString += moreThanZeroTuple(cvc,"SETOP"+String.valueOf(qb.getLevel()));
					}
				}
			}else{
				constraintString+=getEquivalenceConstraints(cvc, qb, qb.getLeftBlockDetails(), qb.getRightBlockDetails());
			}
			
		}

		return constraintString; 

	}
