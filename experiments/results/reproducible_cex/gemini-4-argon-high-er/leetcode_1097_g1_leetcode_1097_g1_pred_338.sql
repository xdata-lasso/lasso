WITH INSTALL_DATE AS (SELECT PLAYER_ID, DEVICE_ID, EVENT_DATE, ROW_NUMBER() OVER (PARTITION BY PLAYER_ID ORDER BY EVENT_DATE) AS ROW_NUM FROM ACTIVITY), DAY_INSTALLS AS (SELECT EVENT_DATE, PLAYER_ID FROM INSTALL_DATE WHERE ROW_NUM = 1), SECOND_LOG AS (SELECT PLAYER_ID, EVENT_DATE AS SECOND_LOG FROM INSTALL_DATE WHERE ROW_NUM = 2), INSTALL_COUNTS AS (SELECT DI.EVENT_DATE, COUNT(PLAYER_ID) AS INSTALLS FROM DAY_INSTALLS AS DI GROUP BY 1), ALMOST AS (SELECT I.PLAYER_ID, I.EVENT_DATE, SECOND_LOG, CAST((JULIANDAY(SECOND_LOG) - JULIANDAY(EVENT_DATE)) AS INTEGER) AS DIFF FROM DAY_INSTALLS AS I LEFT JOIN SECOND_LOG AS S ON S.PLAYER_ID = I.PLAYER_ID), FINAL AS (SELECT EVENT_DATE, COUNT(PLAYER_ID) AS PLAYERS FROM ALMOST WHERE DIFF = 1 GROUP BY 1) SELECT IC.EVENT_DATE AS INSTALL_DT, INSTALLS, ROUND((CAST(COALESCE(PLAYERS, 0) AS REAL) / INSTALLS), 2) AS DAY1_RETENTION FROM INSTALL_COUNTS AS IC LEFT JOIN FINAL AS F ON IC.EVENT_DATE = F.EVENT_DATE;

