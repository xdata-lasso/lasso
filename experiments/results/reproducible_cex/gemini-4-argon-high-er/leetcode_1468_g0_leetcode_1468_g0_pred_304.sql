-- Prediction Query
WITH TAX_RATE AS (SELECT COMPANY_ID, CASE WHEN MAX(SALARY) < 1000 THEN 0 WHEN MAX(SALARY) > 1000 AND MAX(SALARY) < 10000 THEN CAST(24 AS REAL) / 100 WHEN MAX(SALARY) > 10000 THEN CAST(49 AS REAL) / 100 END AS TAX_RATE FROM SALARIES GROUP BY COMPANY_ID) SELECT E.COMPANY_ID, EMPLOYEE_ID, EMPLOYEE_NAME, ROUND(SALARY - SALARY * TAX_RATE) AS SALARY FROM SALARIES AS E JOIN TAX_RATE AS T ON E.COMPANY_ID = T.COMPANY_ID;

