-- Schema DDL
CREATE TABLE "CUSTOMERS" (
    "CUSTOMER_ID" INT,
    "CUSTOMER_DETAILS" TEXT,
    PRIMARY KEY ("CUSTOMER_ID")
);
CREATE TABLE "PROPERTIES" (
    "PROPERTY_ID" INT,
    "PROPERTY_TYPE_CODE" TEXT,
    "PROPERTY_ADDRESS" TEXT,
    "OTHER_DETAILS" TEXT,
    PRIMARY KEY ("PROPERTY_ID")
);
CREATE TABLE "RESIDENTS" (
    "RESIDENT_ID" INT,
    "PROPERTY_ID" INT,
    "DATE_MOVED_IN" DATETIME,
    "DATE_MOVED_OUT" DATETIME,
    "OTHER_DETAILS" TEXT,
    PRIMARY KEY ("RESIDENT_ID", "PROPERTY_ID", "DATE_MOVED_IN"),
    UNIQUE ("RESIDENT_ID"),
    UNIQUE ("PROPERTY_ID"),
    UNIQUE ("DATE_MOVED_IN"),
    FOREIGN KEY ("PROPERTY_ID") REFERENCES "PROPERTIES"("PROPERTY_ID")
);
CREATE TABLE "ORGANIZATIONS" (
    "ORGANIZATION_ID" INT,
    "PARENT_ORGANIZATION_ID" INT,
    "ORGANIZATION_DETAILS" TEXT,
    PRIMARY KEY ("ORGANIZATION_ID")
);
CREATE TABLE "SERVICES" (
    "SERVICE_ID" INT,
    "ORGANIZATION_ID" INT,
    "SERVICE_TYPE_CODE" TEXT,
    "SERVICE_DETAILS" TEXT,
    PRIMARY KEY ("SERVICE_ID"),
    FOREIGN KEY ("ORGANIZATION_ID") REFERENCES "ORGANIZATIONS"("ORGANIZATION_ID")
);
CREATE TABLE "RESIDENTS_SERVICES" (
    "RESIDENT_ID" INT,
    "SERVICE_ID" INT,
    "PROPERTY_ID" INT,
    "DATE_MOVED_IN" DATETIME,
    "DATE_REQUESTED" DATETIME,
    "DATE_PROVIDED" DATETIME,
    "OTHER_DETAILS" TEXT,
    PRIMARY KEY ("RESIDENT_ID", "SERVICE_ID"),
    FOREIGN KEY ("RESIDENT_ID") REFERENCES "RESIDENTS"("RESIDENT_ID"),
    FOREIGN KEY ("PROPERTY_ID") REFERENCES "RESIDENTS"("PROPERTY_ID"),
    FOREIGN KEY ("DATE_MOVED_IN") REFERENCES "RESIDENTS"("DATE_MOVED_IN"),
    FOREIGN KEY ("SERVICE_ID") REFERENCES "SERVICES"("SERVICE_ID")
);
CREATE TABLE "THINGS" (
    "THING_ID" INT,
    "ORGANIZATION_ID" INT,
    "TYPE_OF_THING_CODE" TEXT,
    "SERVICE_TYPE_CODE" TEXT,
    "SERVICE_DETAILS" TEXT,
    PRIMARY KEY ("THING_ID"),
    FOREIGN KEY ("ORGANIZATION_ID") REFERENCES "ORGANIZATIONS"("ORGANIZATION_ID")
);
CREATE TABLE "CUSTOMER_EVENTS" (
    "CUSTOMER_EVENT_ID" INT,
    "RESIDENT_ID" INT,
    "PROPERTY_ID" INT,
    "DATE_MOVED_IN" DATETIME,
    "CUSTOMER_ID" INT,
    "THING_ID" INT,
    PRIMARY KEY ("CUSTOMER_EVENT_ID"),
    FOREIGN KEY ("RESIDENT_ID") REFERENCES "RESIDENTS"("RESIDENT_ID"),
    FOREIGN KEY ("PROPERTY_ID") REFERENCES "RESIDENTS"("PROPERTY_ID"),
    FOREIGN KEY ("DATE_MOVED_IN") REFERENCES "RESIDENTS"("DATE_MOVED_IN"),
    FOREIGN KEY ("CUSTOMER_ID") REFERENCES "CUSTOMERS"("CUSTOMER_ID"),
    FOREIGN KEY ("THING_ID") REFERENCES "THINGS"("THING_ID")
);
CREATE TABLE "CUSTOMER_EVENT_NOTES" (
    "CUSTOMER_EVENT_NOTE_ID" INT,
    "CUSTOMER_EVENT_ID" INT,
    "SERVICE_TYPE_CODE" TEXT,
    "RESIDENT_ID" INT,
    "PROPERTY_ID" INT,
    "DATE_MOVED_IN" DATETIME,
    PRIMARY KEY ("CUSTOMER_EVENT_NOTE_ID"),
    FOREIGN KEY ("CUSTOMER_EVENT_ID") REFERENCES "CUSTOMER_EVENTS"("CUSTOMER_EVENT_ID")
);
CREATE TABLE "TIMED_STATUS_OF_THINGS" (
    "THING_ID" INT,
    "DATE_AND_DATE" DATETIME,
    "STATUS_OF_THING_CODE" TEXT,
    PRIMARY KEY ("THING_ID", "DATE_AND_DATE", "STATUS_OF_THING_CODE"),
    FOREIGN KEY ("THING_ID") REFERENCES "THINGS"("THING_ID")
);
CREATE TABLE "TIMED_LOCATIONS_OF_THINGS" (
    "THING_ID" INT,
    "DATE_AND_TIME" DATETIME,
    "LOCATION_CODE" TEXT,
    PRIMARY KEY ("THING_ID", "DATE_AND_TIME", "LOCATION_CODE"),
    FOREIGN KEY ("THING_ID") REFERENCES "THINGS"("THING_ID")
);

