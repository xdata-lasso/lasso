    FOREIGN KEY ("COMPETITION_ID") REFERENCES "COMPETITION"("COMPETITION_ID"),
    FOREIGN KEY ("CLUB_ID_2") REFERENCES "CLUB"("CLUB_ID"),
    FOREIGN KEY ("CLUB_ID_1") REFERENCES "CLUB"("CLUB_ID")
);

