);
CREATE TABLE "COMPETITION" (
    "COMPETITION_ID" INT,
    "YEAR" FLOAT,
    "COMPETITION_TYPE" TEXT,
    "COUNTRY" TEXT,
    PRIMARY KEY ("COMPETITION_ID")
);
CREATE TABLE "COMPETITION_RESULT" (
    "COMPETITION_ID" INT,
