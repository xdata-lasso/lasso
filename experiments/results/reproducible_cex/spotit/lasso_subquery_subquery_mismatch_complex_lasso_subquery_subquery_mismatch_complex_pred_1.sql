-- Schema DDL
CREATE TABLE "STUDENTS" (
    "STUDENT_ID" INT,
    "FIRST_NAME" TEXT,
    "LAST_NAME" TEXT,
    "ENROLLMENT_YEAR" INT,
    "MAJOR" TEXT,
    PRIMARY KEY ("STUDENT_ID")
);
CREATE TABLE "COURSES" (
    "COURSE_ID" INT,
    "COURSE_CODE" TEXT,
    "COURSE_NAME" TEXT,
    "CREDITS" INT,
    "DEPARTMENT" TEXT,
    PRIMARY KEY ("COURSE_ID")
);
CREATE TABLE "ENROLLMENTS" (
    "ENROLLMENT_ID" INT,
    "STUDENT_ID" INT,
    "COURSE_ID" INT,
    "SEMESTER" TEXT,
    "GRADE" TEXT,
    PRIMARY KEY ("ENROLLMENT_ID"),
    FOREIGN KEY ("COURSE_ID") REFERENCES "COURSES"("COURSE_ID"),
    FOREIGN KEY ("STUDENT_ID") REFERENCES "STUDENTS"("STUDENT_ID")
);
CREATE TABLE "PROFESSORS" (
    "PROFESSOR_ID" INT,
    "NAME" TEXT,
    "DEPARTMENT" TEXT,
    "HIRE_DATE" DATE,
    "SALARY" FLOAT,
    PRIMARY KEY ("PROFESSOR_ID")
);

