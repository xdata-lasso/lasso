CREATE TABLE "MAJOR" (
    "MAJOR_ID" TEXT,
    "MAJOR_NAME" TEXT,
    "DEPARTMENT" TEXT,
    "COLLEGE" TEXT,
    PRIMARY KEY ("MAJOR_ID")
);
