CREATE TABLE "SALARIES" (
    "COMPANY_ID" INT,
    "EMPLOYEE_ID" INT,
    "EMPLOYEE_NAME" TEXT,
    "SALARY" INT,
    PRIMARY KEY ("COMPANY_ID", "EMPLOYEE_ID")
);

-- Loading data
PRAGMA foreign_keys = OFF;
