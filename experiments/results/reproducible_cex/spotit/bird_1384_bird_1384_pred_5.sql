    "BUDGET_ID" TEXT,
    "CATEGORY" TEXT,
    "SPENT" FLOAT,
    "REMAINING" FLOAT,
    "AMOUNT" INT,
    "EVENT_STATUS" TEXT,
    "LINK_TO_EVENT" TEXT,
    PRIMARY KEY ("BUDGET_ID"),
    FOREIGN KEY ("LINK_TO_EVENT") REFERENCES "EVENT"("EVENT_ID")
);
CREATE TABLE "EXPENSE" (
    "EXPENSE_ID" TEXT,
    "EXPENSE_DESCRIPTION" TEXT,
    "EXPENSE_DATE" TEXT,
    "COST" FLOAT,
    "APPROVED" TEXT,
    "LINK_TO_MEMBER" TEXT,
    "LINK_TO_BUDGET" TEXT,
    PRIMARY KEY ("EXPENSE_ID"),
    FOREIGN KEY ("LINK_TO_BUDGET") REFERENCES "BUDGET"("BUDGET_ID"),
    FOREIGN KEY ("LINK_TO_MEMBER") REFERENCES "MEMBER"("MEMBER_ID")
);
CREATE TABLE "INCOME" (
    "INCOME_ID" TEXT,
    "DATE_RECEIVED" TEXT,
    "AMOUNT" INT,
    "SOURCE" TEXT,
    "NOTES" TEXT,
    "LINK_TO_MEMBER" TEXT,
    PRIMARY KEY ("INCOME_ID"),
    FOREIGN KEY ("LINK_TO_MEMBER") REFERENCES "MEMBER"("MEMBER_ID")
);
CREATE TABLE "MEMBER" (
    "MEMBER_ID" TEXT,
    "FIRST_NAME" TEXT,
    "LAST_NAME" TEXT,
    "EMAIL" TEXT,
    "POSITION" TEXT,
    "T_SHIRT_SIZE" TEXT,
    "PHONE" TEXT,
    "ZIP" INT,
    "LINK_TO_MAJOR" TEXT,
    PRIMARY KEY ("MEMBER_ID"),
    FOREIGN KEY ("LINK_TO_MAJOR") REFERENCES "MAJOR"("MAJOR_ID"),
    FOREIGN KEY ("ZIP") REFERENCES "ZIP_CODE"("ZIP_CODE")
