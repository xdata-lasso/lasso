CREATE TABLE "DEPARTMENTS" (
    "DEPARTMENT_ID" INT,
    "DEPARTMENT_NAME" TEXT,
    "MANAGER_ID" INT,
    "LOCATION" TEXT,
    PRIMARY KEY ("DEPARTMENT_ID")
);
CREATE TABLE "EMPLOYEES" (
    "EMPLOYEE_ID" INT,
    "FIRST_NAME" TEXT,
    "LAST_NAME" TEXT,
    "EMAIL" TEXT,
    "PHONE" TEXT,
    "HIRE_DATE" DATE,
    "JOB_ID" TEXT,
    "SALARY" FLOAT,
    "COMMISSION_PCT" FLOAT,
    "MANAGER_ID" INT,
    "DEPARTMENT_ID" INT,
    PRIMARY KEY ("EMPLOYEE_ID"),
    FOREIGN KEY ("DEPARTMENT_ID") REFERENCES "DEPARTMENTS"("DEPARTMENT_ID"),
    FOREIGN KEY ("JOB_ID") REFERENCES "JOBS"("JOB_ID")
);
CREATE TABLE "JOBS" (
    "JOB_ID" TEXT,
    "JOB_TITLE" TEXT,
    "MIN_SALARY" FLOAT,
    "MAX_SALARY" FLOAT,
    PRIMARY KEY ("JOB_ID")
);
CREATE TABLE "JOBHISTORY" (
    "EMPLOYEE_ID" INT,
    "START_DATE" DATE,
    "END_DATE" DATE,
    "JOB_ID" TEXT,
    "DEPARTMENT_ID" INT,
    FOREIGN KEY ("EMPLOYEE_ID") REFERENCES "EMPLOYEES"("EMPLOYEE_ID"),
    FOREIGN KEY ("DEPARTMENT_ID") REFERENCES "DEPARTMENTS"("DEPARTMENT_ID"),
    FOREIGN KEY ("JOB_ID") REFERENCES "JOBS"("JOB_ID")
);

