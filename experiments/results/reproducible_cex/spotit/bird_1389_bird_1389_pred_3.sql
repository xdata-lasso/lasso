    FOREIGN KEY ("LINK_TO_MEMBER") REFERENCES "MEMBER"("MEMBER_ID")
);
CREATE TABLE "INCOME" (
    "INCOME_ID" TEXT,
    "DATE_RECEIVED" TEXT,
    "AMOUNT" INT,
    "SOURCE" TEXT,
    "NOTES" TEXT,
    "LINK_TO_MEMBER" TEXT,
    PRIMARY KEY ("INCOME_ID"),
    FOREIGN KEY ("LINK_TO_MEMBER") REFERENCES "MEMBER"("MEMBER_ID")
);
CREATE TABLE "MEMBER" (
    "MEMBER_ID" TEXT,
    "FIRST_NAME" TEXT,
    "LAST_NAME" TEXT,
    "EMAIL" TEXT,
