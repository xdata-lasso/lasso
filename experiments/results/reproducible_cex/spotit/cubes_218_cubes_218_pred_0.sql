    "PETID" INT,
    FOREIGN KEY ("STUID") REFERENCES "STUDENT"("STUID"),
    FOREIGN KEY ("PETID") REFERENCES "PETS"("PETID")
);
CREATE TABLE "PETS" (
    "PETID" INT,
    "PETTYPE" TEXT,
    "PET_AGE" INT,
    "WEIGHT" FLOAT,
    PRIMARY KEY ("PETID")
);

