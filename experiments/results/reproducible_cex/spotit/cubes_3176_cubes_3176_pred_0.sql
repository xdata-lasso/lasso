CREATE TABLE "STUDENT" (
    "STUID" INT,
    "LNAME" TEXT,
    "FNAME" TEXT,
    "AGE" INT,
    "SEX" TEXT,
    "MAJOR" INT,
    "ADVISOR" INT,
    "CITY_CODE" TEXT,
    PRIMARY KEY ("STUID")
);
CREATE TABLE "RESTAURANT" (
    "RESID" INT,
    "RESNAME" TEXT,
    "ADDRESS" TEXT,
    "RATING" INT,
    PRIMARY KEY ("RESID")
);
CREATE TABLE "TYPE_OF_RESTAURANT" (
    "RESTYPEID" INT,
    "RESID" INT,
    FOREIGN KEY ("RESTYPEID") REFERENCES "RESTAURANT_TYPE"("RESTYPEID"),
    FOREIGN KEY ("RESID") REFERENCES "RESTAURANT"("RESID")
);
CREATE TABLE "RESTAURANT_TYPE" (
    "RESTYPEID" INT,
    "RESTYPENAME" TEXT,
    "RESTYPEDESCRIPTION" TEXT,
    PRIMARY KEY ("RESTYPEID")
);
CREATE TABLE "VISITS_RESTAURANT" (
    "RESID" INT,
    "STUID" INT,
    "TIME" TIMESTAMPTZ,
    "SPENT" FLOAT,
    FOREIGN KEY ("RESID") REFERENCES "RESTAURANT"("RESID"),
    FOREIGN KEY ("STUID") REFERENCES "STUDENT"("STUID")
);

