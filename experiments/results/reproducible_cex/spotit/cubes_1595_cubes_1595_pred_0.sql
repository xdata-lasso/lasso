);
CREATE TABLE "DOCUMENTS" (
    "DOCUMENT_ID" INT,
    "SHIPPING_AGENT_CODE" TEXT,
    "DOCUMENT_STATUS_CODE" TEXT,
    "DOCUMENT_TYPE_CODE" TEXT,
    "RECEIPT_DATE" DATETIME,
