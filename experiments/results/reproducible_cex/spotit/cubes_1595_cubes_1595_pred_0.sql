    FOREIGN KEY ("DOCUMENT_STATUS_CODE") REFERENCES "REF_DOCUMENT_STATUS"("DOCUMENT_STATUS_CODE"),
    FOREIGN KEY ("DOCUMENT_TYPE_CODE") REFERENCES "REF_DOCUMENT_TYPES"("DOCUMENT_TYPE_CODE")
