-- Schema DDL
CREATE TABLE "CUSTOMERS" (
    "CUSTOMER_ID" INT,
    "CUSTOMER_FIRST_NAME" TEXT,
    "CUSTOMER_MIDDLE_INITIAL" TEXT,
    "CUSTOMER_LAST_NAME" TEXT,
    "GENDER" TEXT,
    "EMAIL_ADDRESS" TEXT,
    "LOGIN_NAME" TEXT,
    "LOGIN_PASSWORD" TEXT,
    "PHONE_NUMBER" TEXT,
    "TOWN_CITY" TEXT,
    "STATE_COUNTY_PROVINCE" TEXT,
    "COUNTRY" TEXT,
    PRIMARY KEY ("CUSTOMER_ID")
);
CREATE TABLE "ORDERS" (
    "ORDER_ID" INT,
    "CUSTOMER_ID" INT,
    "DATE_ORDER_PLACED" DATETIME,
    "ORDER_DETAILS" TEXT,
    PRIMARY KEY ("ORDER_ID"),
    FOREIGN KEY ("CUSTOMER_ID") REFERENCES "CUSTOMERS"("CUSTOMER_ID")
);
CREATE TABLE "INVOICES" (
    "INVOICE_NUMBER" INT,
    "ORDER_ID" INT,
    "INVOICE_DATE" DATETIME,
    PRIMARY KEY ("INVOICE_NUMBER"),
    FOREIGN KEY ("ORDER_ID") REFERENCES "ORDERS"("ORDER_ID")
);
CREATE TABLE "ACCOUNTS" (
    "ACCOUNT_ID" INT,
    "CUSTOMER_ID" INT,
    "DATE_ACCOUNT_OPENED" DATETIME,
    "ACCOUNT_NAME" TEXT,
    "OTHER_ACCOUNT_DETAILS" TEXT,
    PRIMARY KEY ("ACCOUNT_ID"),
    FOREIGN KEY ("CUSTOMER_ID") REFERENCES "CUSTOMERS"("CUSTOMER_ID")
);
CREATE TABLE "PRODUCT_CATEGORIES" (
    "PRODUCTION_TYPE_CODE" TEXT,
    "PRODUCT_TYPE_DESCRIPTION" TEXT,
    "VAT_RATING" FLOAT,
    PRIMARY KEY ("PRODUCTION_TYPE_CODE")
);
CREATE TABLE "PRODUCTS" (
    "PRODUCT_ID" INT,
    "PRODUCTION_TYPE_CODE" TEXT,
    "PARENT_PRODUCT_ID" INT,
    "UNIT_PRICE" FLOAT,
    "PRODUCT_NAME" TEXT,
    "PRODUCT_COLOR" TEXT,
    "PRODUCT_SIZE" TEXT,
    PRIMARY KEY ("PRODUCT_ID"),
    FOREIGN KEY ("PRODUCTION_TYPE_CODE") REFERENCES "PRODUCT_CATEGORIES"("PRODUCTION_TYPE_CODE")
);
CREATE TABLE "FINANCIAL_TRANSACTIONS" (
    "ACCOUNT_ID" INT,
    "INVOICE_NUMBER" INT,
    "TRANSACTION_ID" INT,
    "TRANSACTION_TYPE" TEXT,
    "TRANSACTION_DATE" DATETIME,
    "TRANSACTION_AMOUNT" FLOAT,
    "TRANSACTION_COMMENT" TEXT,
    "OTHER_TRANSACTION_DETAILS" TEXT,
    FOREIGN KEY ("ACCOUNT_ID") REFERENCES "ACCOUNTS"("ACCOUNT_ID"),
    FOREIGN KEY ("INVOICE_NUMBER") REFERENCES "INVOICES"("INVOICE_NUMBER")
);
CREATE TABLE "ORDER_ITEMS" (
    "ORDER_ITEM_ID" INT,
    "ORDER_ID" INT,
    "PRODUCT_ID" INT,
    "PRODUCT_QUANTITY" TEXT,
    "OTHER_ORDER_ITEM_DETAILS" TEXT,
    PRIMARY KEY ("ORDER_ITEM_ID"),
    FOREIGN KEY ("ORDER_ID") REFERENCES "ORDERS"("ORDER_ID"),
    FOREIGN KEY ("PRODUCT_ID") REFERENCES "PRODUCTS"("PRODUCT_ID")
);
CREATE TABLE "INVOICE_LINE_ITEMS" (
    "PRODUCT_ID" INT,
    "INVOICE_NUMBER" INT,
    "ORDER_ITEM_ID" INT,
    "PRODUCT_TITLE" TEXT,
    "PRODUCT_QUANTITY" TEXT,
    "PRODUCT_PRICE" FLOAT,
    "DERIVED_PRODUCT_COST" FLOAT,
    "DERIVED_VAT_PAYABLE" FLOAT,
    "DERIVED_TOTAL_COST" FLOAT,
    FOREIGN KEY ("PRODUCT_ID") REFERENCES "PRODUCTS"("PRODUCT_ID"),
    FOREIGN KEY ("INVOICE_NUMBER") REFERENCES "INVOICES"("INVOICE_NUMBER"),
    FOREIGN KEY ("ORDER_ITEM_ID") REFERENCES "ORDER_ITEMS"("ORDER_ITEM_ID")
);

