CREATE TABLE "AIRCRAFT" (
    "AID" FLOAT,
    "NAME" TEXT,
    "DISTANCE" FLOAT,
    PRIMARY KEY ("AID")
);
CREATE TABLE "EMPLOYEE" (
    "EID" FLOAT,
    "NAME" TEXT,
    "SALARY" FLOAT,
    PRIMARY KEY ("EID")
);
CREATE TABLE "CERTIFICATE" (
    "EID" FLOAT,
    "AID" FLOAT,
    PRIMARY KEY ("EID", "AID"),
    FOREIGN KEY ("AID") REFERENCES "AIRCRAFT"("AID"),
    FOREIGN KEY ("EID") REFERENCES "EMPLOYEE"("EID")
);

