    "USER_NAME" TEXT,
    "USER_LOGIN" TEXT,
    "PASSWORD" TEXT,
    PRIMARY KEY ("USER_ID"),
    FOREIGN KEY ("ROLE_CODE") REFERENCES "ROLES"("ROLE_CODE")
