CREATE TABLE "ADDRESSES" (
    "ADDRESS_ID" INT,
    "LINE_1" TEXT,
    "LINE_2" TEXT,
    "LINE_3" TEXT,
    "CITY" TEXT,
    "ZIP_POSTCODE" TEXT,
    "STATE_PROVINCE_COUNTY" TEXT,
    "COUNTRY" TEXT,
    "OTHER_ADDRESS_DETAILS" TEXT,
    PRIMARY KEY ("ADDRESS_ID")
);
CREATE TABLE "COURSES" (
    "COURSE_ID" INT,
    "COURSE_NAME" TEXT,
    "COURSE_DESCRIPTION" TEXT,
    "OTHER_DETAILS" TEXT,
    PRIMARY KEY ("COURSE_ID")
);
CREATE TABLE "DEPARTMENTS" (
    "DEPARTMENT_ID" INT,
    "DEPARTMENT_NAME" TEXT,
    "DEPARTMENT_DESCRIPTION" TEXT,
    "OTHER_DETAILS" TEXT,
    PRIMARY KEY ("DEPARTMENT_ID")
);
CREATE TABLE "DEGREE_PROGRAMS" (
    "DEGREE_PROGRAM_ID" INT,
    "DEPARTMENT_ID" INT,
    "DEGREE_SUMMARY_NAME" TEXT,
    "DEGREE_SUMMARY_DESCRIPTION" TEXT,
    "OTHER_DETAILS" TEXT,
    PRIMARY KEY ("DEGREE_PROGRAM_ID"),
    FOREIGN KEY ("DEPARTMENT_ID") REFERENCES "DEPARTMENTS"("DEPARTMENT_ID")
);
CREATE TABLE "SECTIONS" (
    "SECTION_ID" INT,
    "COURSE_ID" INT,
    "SECTION_NAME" TEXT,
    "SECTION_DESCRIPTION" TEXT,
    "OTHER_DETAILS" TEXT,
    PRIMARY KEY ("SECTION_ID"),
    FOREIGN KEY ("COURSE_ID") REFERENCES "COURSES"("COURSE_ID")
);
CREATE TABLE "SEMESTERS" (
    "SEMESTER_ID" INT,
    "SEMESTER_NAME" TEXT,
    "SEMESTER_DESCRIPTION" TEXT,
    "OTHER_DETAILS" TEXT,
    PRIMARY KEY ("SEMESTER_ID")
);
CREATE TABLE "STUDENTS" (
    "STUDENT_ID" INT,
    "PERMANENT_ADDRESS_ID" INT,
    "CURRENT_ADDRESS_ID" INT,
    "FIRST_NAME" TEXT,
    "MIDDLE_NAME" TEXT,
    "LAST_NAME" TEXT,
    "CELL_MOBILE_NUMBER" TEXT,
    "EMAIL_ADDRESS" TEXT,
    "SSN" TEXT,
    "DATE_FIRST_REGISTERED" DATETIME,
    "DATE_LEFT" DATETIME,
    "OTHER_STUDENT_DETAILS" TEXT,
    PRIMARY KEY ("STUDENT_ID"),
    FOREIGN KEY ("PERMANENT_ADDRESS_ID") REFERENCES "ADDRESSES"("ADDRESS_ID"),
    FOREIGN KEY ("CURRENT_ADDRESS_ID") REFERENCES "ADDRESSES"("ADDRESS_ID")
);
CREATE TABLE "STUDENT_ENROLMENT" (
    "STUDENT_ENROLMENT_ID" INT,
    "STUDENT_ID" INT,
    "SEMESTER_ID" INT,
    "DEGREE_PROGRAM_ID" INT,
    "OTHER_DETAILS" TEXT,
    PRIMARY KEY ("STUDENT_ENROLMENT_ID"),
    FOREIGN KEY ("STUDENT_ID") REFERENCES "STUDENTS"("STUDENT_ID"),
    FOREIGN KEY ("SEMESTER_ID") REFERENCES "SEMESTERS"("SEMESTER_ID"),
    FOREIGN KEY ("DEGREE_PROGRAM_ID") REFERENCES "DEGREE_PROGRAMS"("DEGREE_PROGRAM_ID")
);
CREATE TABLE "STUDENT_ENROLMENT_COURSES" (
    "STUDENT_COURSE_ID" INT,
    "STUDENT_ENROLMENT_ID" INT,
    "COURSE_ID" INT,
    PRIMARY KEY ("STUDENT_COURSE_ID"),
    FOREIGN KEY ("STUDENT_ENROLMENT_ID") REFERENCES "STUDENT_ENROLMENT"("STUDENT_ENROLMENT_ID"),
    FOREIGN KEY ("COURSE_ID") REFERENCES "COURSES"("COURSE_ID")
);
CREATE TABLE "TRANSCRIPTS" (
    "TRANSCRIPT_ID" INT,
    "TRANSCRIPT_DATE" DATETIME,
    "OTHER_DETAILS" TEXT,
    PRIMARY KEY ("TRANSCRIPT_ID")
);
CREATE TABLE "TRANSCRIPT_CONTENTS" (
    "TRANSCRIPT_ID" INT,
    "STUDENT_COURSE_ID" INT,
    FOREIGN KEY ("TRANSCRIPT_ID") REFERENCES "TRANSCRIPTS"("TRANSCRIPT_ID"),
    FOREIGN KEY ("STUDENT_COURSE_ID") REFERENCES "STUDENT_ENROLMENT_COURSES"("STUDENT_COURSE_ID")
);

