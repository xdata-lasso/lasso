-- Schema DDL
CREATE TABLE "CITY" (
    "ID" INT,
    "COUNTRYCODE" TEXT,
    "NAME" TEXT,
    "DISTRICT" TEXT,
    "POPULATION" INT,
    PRIMARY KEY ("ID"),
    FOREIGN KEY ("COUNTRYCODE") REFERENCES "COUNTRY"("CODE")
);
CREATE TABLE "COUNTRY" (
    "CODE" TEXT,
    "NAME" TEXT,
    "CONTINENT" TEXT,
    "REGION" TEXT,
    "SURFACEAREA" FLOAT,
    "INDEPYEAR" INT,
    "POPULATION" INT,
    "LIFEEXPECTANCY" FLOAT,
    "GNP" FLOAT,
    "GNPOLD" FLOAT,
    "LOCALNAME" TEXT,
    "GOVERNMENTFORM" TEXT,
    "HEADOFSTATE" TEXT,
    "CAPITAL" INT,
    "CODE2" TEXT,
    PRIMARY KEY ("CODE")
);
CREATE TABLE "COUNTRYLANGUAGE" (
    "COUNTRYCODE" TEXT,
    "LANGUAGE" TEXT,
    "ISOFFICIAL" TEXT,
    "PERCENTAGE" FLOAT,
    PRIMARY KEY ("LANGUAGE", "COUNTRYCODE"),
    FOREIGN KEY ("COUNTRYCODE") REFERENCES "COUNTRY"("CODE")
);

