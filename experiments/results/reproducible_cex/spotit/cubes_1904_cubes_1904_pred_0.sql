    FOREIGN KEY ("DOCUMENT_ID") REFERENCES "ALL_DOCUMENTS"("DOCUMENT_ID"),
    FOREIGN KEY ("ACTUAL_DESTRUCTION_DATE") REFERENCES "REF_CALENDAR"("CALENDAR_DATE"),
