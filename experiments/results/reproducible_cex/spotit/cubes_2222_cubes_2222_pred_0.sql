-- Schema DDL
CREATE TABLE "COUNTRY" (
    "ID" FLOAT,
    "NAME" TEXT,
    PRIMARY KEY ("ID")
);
CREATE TABLE "LEAGUE" (
    "ID" FLOAT,
    "COUNTRY_ID" FLOAT,
    "NAME" TEXT,
    PRIMARY KEY ("ID"),
    FOREIGN KEY ("COUNTRY_ID") REFERENCES "COUNTRY"("ID")
);
CREATE TABLE "TEAM" (
    "ID" FLOAT,
    "TEAM_API_ID" FLOAT,
    "TEAM_FIFA_API_ID" FLOAT,
    "TEAM_LONG_NAME" TEXT,
    "TEAM_SHORT_NAME" TEXT,
    PRIMARY KEY ("ID"),
    UNIQUE ("TEAM_API_ID")
);
CREATE TABLE "TEAM_ATTRIBUTES" (
    "ID" FLOAT,
    "TEAM_API_ID" FLOAT,
    "DATE" TEXT,
    "BUILDUPPLAYSPEED" FLOAT,
    PRIMARY KEY ("ID"),
    FOREIGN KEY ("TEAM_API_ID") REFERENCES "TEAM"("TEAM_API_ID")
);
CREATE TABLE "PLAYER" (
    "ID" FLOAT,
    "PLAYER_API_ID" FLOAT,
    "PLAYER_NAME" TEXT,
    "PLAYER_FIFA_API_ID" FLOAT,
    "BIRTHDAY" TEXT,
    "HEIGHT" FLOAT,
    "WEIGHT" FLOAT,
    PRIMARY KEY ("ID"),
    UNIQUE ("PLAYER_API_ID")
);
CREATE TABLE "PLAYER_ATTRIBUTES" (
    "ID" FLOAT,
    "PLAYER_API_ID" FLOAT,
    "DATE" TEXT,
    "OVERALL_RATING" FLOAT,
    "POTENTIAL" FLOAT,
    PRIMARY KEY ("ID"),
    FOREIGN KEY ("PLAYER_API_ID") REFERENCES "PLAYER"("PLAYER_API_ID")
);
CREATE TABLE "MATCH" (
    "ID" FLOAT,
    "COUNTRY_ID" FLOAT,
    "LEAGUE_ID" FLOAT,
    "HOME_TEAM_API_ID" FLOAT,
    "AWAY_TEAM_API_ID" FLOAT,
    "SEASON" TEXT,
    "STAGE" FLOAT,
    "DATE" TEXT,
    "MATCH_API_ID" FLOAT,
    "HOME_TEAM_GOAL" FLOAT,
    "AWAY_TEAM_GOAL" FLOAT,
    PRIMARY KEY ("ID"),
    FOREIGN KEY ("COUNTRY_ID") REFERENCES "COUNTRY"("ID"),
    FOREIGN KEY ("LEAGUE_ID") REFERENCES "LEAGUE"("ID"),
    FOREIGN KEY ("HOME_TEAM_API_ID") REFERENCES "TEAM"("TEAM_API_ID"),
    FOREIGN KEY ("AWAY_TEAM_API_ID") REFERENCES "TEAM"("TEAM_API_ID")
);

