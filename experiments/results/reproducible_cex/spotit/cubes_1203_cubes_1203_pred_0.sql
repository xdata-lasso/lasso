    "EVENT_ID" INT,
    "FINANCE_ID" INT,
    "ADDRESS_ID" INT,
    "LOCATION_ID" INT,
    "CHANNEL_ID" INT,
    "EVENT_TYPE_CODE" TEXT,
    PRIMARY KEY ("EVENT_ID"),
    FOREIGN KEY ("FINANCE_ID") REFERENCES "FINANCES"("FINANCE_ID"),
