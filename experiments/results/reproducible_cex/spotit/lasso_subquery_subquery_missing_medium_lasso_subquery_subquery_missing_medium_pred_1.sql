-- Schema DDL
CREATE TABLE "USERS" (
    "USER_ID" INT,
    "NAME" TEXT,
    "EMAIL" TEXT,
    "REGISTRATION_DATE" DATE,
    "IS_ACTIVE" INT,
    PRIMARY KEY ("USER_ID")
);
CREATE TABLE "ORDERS" (
    "ORDER_ID" INT,
    "USER_ID" INT,
    "ORDER_DATE" DATE,
    "TOTAL_AMOUNT" FLOAT,
    "STATUS" TEXT,
    PRIMARY KEY ("ORDER_ID"),
    FOREIGN KEY ("USER_ID") REFERENCES "USERS"("USER_ID")
);
CREATE TABLE "PRODUCTS" (
    "PRODUCT_ID" INT,
    "NAME" TEXT,
    "CATEGORY" TEXT,
    "PRICE" FLOAT,
    "STOCK_QUANTITY" INT,
    PRIMARY KEY ("PRODUCT_ID")
);
CREATE TABLE "ORDERITEMS" (
    "ORDER_ITEM_ID" INT,
    "ORDER_ID" INT,
    "PRODUCT_ID" INT,
    "QUANTITY" INT,
    "UNIT_PRICE" FLOAT,
    PRIMARY KEY ("ORDER_ITEM_ID"),
    FOREIGN KEY ("PRODUCT_ID") REFERENCES "PRODUCTS"("PRODUCT_ID"),
    FOREIGN KEY ("ORDER_ID") REFERENCES "ORDERS"("ORDER_ID")
);

