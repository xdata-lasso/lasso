    "DISTRICT_ID" INT,
    "DISTRICT_NAME" TEXT,
    "HEADQUARTERED_CITY" TEXT,
    "CITY_POPULATION" FLOAT,
    "CITY_AREA" FLOAT,
    PRIMARY KEY ("DISTRICT_ID")
