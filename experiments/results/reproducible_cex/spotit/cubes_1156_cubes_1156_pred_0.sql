    "STORE_ID" INT,
    "DISTRICT_ID" INT,
    PRIMARY KEY ("STORE_ID"),
    FOREIGN KEY ("DISTRICT_ID") REFERENCES "DISTRICT"("DISTRICT_ID"),
    FOREIGN KEY ("STORE_ID") REFERENCES "STORE"("STORE_ID")
);

