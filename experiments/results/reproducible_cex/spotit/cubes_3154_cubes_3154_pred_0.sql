-- Schema DDL
CREATE TABLE "CUSTOMERS" (
    "CUSTOMER_ID" INT,
    "CUSTOMER_NAME" TEXT,
    PRIMARY KEY ("CUSTOMER_ID")
);
CREATE TABLE "SERVICES" (
    "SERVICE_ID" INT,
    "SERVICE_NAME" TEXT,
    PRIMARY KEY ("SERVICE_ID")
);
CREATE TABLE "AVAILABLE_POLICIES" (
    "POLICY_ID" INT,
    "POLICY_TYPE_CODE" TEXT,
    "CUSTOMER_PHONE" TEXT,
    PRIMARY KEY ("POLICY_ID")
);
CREATE TABLE "CUSTOMERS_POLICIES" (
    "CUSTOMER_ID" INT,
    "POLICY_ID" INT,
    "DATE_OPENED" DATE,
    "DATE_CLOSED" DATE,
    PRIMARY KEY ("CUSTOMER_ID", "POLICY_ID"),
    UNIQUE ("CUSTOMER_ID"),
    UNIQUE ("POLICY_ID"),
    FOREIGN KEY ("POLICY_ID") REFERENCES "AVAILABLE_POLICIES"("POLICY_ID"),
    FOREIGN KEY ("CUSTOMER_ID") REFERENCES "CUSTOMERS"("CUSTOMER_ID")
);
CREATE TABLE "FIRST_NOTIFICATION_OF_LOSS" (
    "FNOL_ID" INT,
    "CUSTOMER_ID" INT,
    "POLICY_ID" INT,
    "SERVICE_ID" INT,
    PRIMARY KEY ("FNOL_ID"),
    FOREIGN KEY ("CUSTOMER_ID") REFERENCES "CUSTOMERS_POLICIES"("CUSTOMER_ID"),
    FOREIGN KEY ("POLICY_ID") REFERENCES "CUSTOMERS_POLICIES"("POLICY_ID"),
    FOREIGN KEY ("SERVICE_ID") REFERENCES "SERVICES"("SERVICE_ID")
);
CREATE TABLE "CLAIMS" (
    "CLAIM_ID" INT,
    "FNOL_ID" INT,
    "EFFECTIVE_DATE" DATE,
    PRIMARY KEY ("CLAIM_ID"),
    FOREIGN KEY ("FNOL_ID") REFERENCES "FIRST_NOTIFICATION_OF_LOSS"("FNOL_ID")
);
CREATE TABLE "SETTLEMENTS" (
    "SETTLEMENT_ID" INT,
    "CLAIM_ID" INT,
    "EFFECTIVE_DATE" DATE,
    "SETTLEMENT_AMOUNT" FLOAT,
    PRIMARY KEY ("SETTLEMENT_ID"),
    FOREIGN KEY ("CLAIM_ID") REFERENCES "CLAIMS"("CLAIM_ID")
);

