);
CREATE TABLE "TEAM" (
    "TEAM_ID" INT,
    "NAME" TEXT,
    PRIMARY KEY ("TEAM_ID")
);
CREATE TABLE "MATCH_SEASON" (
    "SEASON" FLOAT,
    "TEAM" INT,
    "COUNTRY" INT,
    "PLAYER" TEXT,
    "POSITION" TEXT,
    "DRAFT_PICK_NUMBER" INT,
    "DRAFT_CLASS" TEXT,
    "COLLEGE" TEXT,
    PRIMARY KEY ("SEASON"),
    FOREIGN KEY ("TEAM") REFERENCES "TEAM"("TEAM_ID"),
    FOREIGN KEY ("COUNTRY") REFERENCES "COUNTRY"("COUNTRY_ID")
);
CREATE TABLE "PLAYER" (
    "PLAYER_ID" INT,
    "TEAM" INT,
    "PLAYER" TEXT,
    "YEARS_PLAYED" TEXT,
    "TOTAL_WL" TEXT,
    "SINGLES_WL" TEXT,
    "DOUBLES_WL" TEXT,
    PRIMARY KEY ("PLAYER_ID"),
    FOREIGN KEY ("TEAM") REFERENCES "TEAM"("TEAM_ID")
);

