-- Schema DDL
CREATE TABLE "STUDENT" (
    "STUID" INT,
    "LNAME" TEXT,
    "FNAME" TEXT,
    "AGE" INT,
    "SEX" TEXT,
    "MAJOR" INT,
    "ADVISOR" INT,
    "CITY_CODE" TEXT,
    PRIMARY KEY ("STUID")
);
CREATE TABLE "FACULTY" (
    "FACID" INT,
    "LNAME" TEXT,
    "FNAME" TEXT,
    "RANK" TEXT,
    "SEX" TEXT,
    "PHONE" INT,
    "ROOM" TEXT,
    "BUILDING" TEXT,
    PRIMARY KEY ("FACID")
);
CREATE TABLE "DEPARTMENT" (
    "DNO" INT,
    "DIVISION" TEXT,
    "DNAME" TEXT,
    "ROOM" TEXT,
    "BUILDING" TEXT,
    "DPHONE" INT,
    PRIMARY KEY ("DNO")
);
CREATE TABLE "MEMBER_OF" (
    "DNO" INT,
    "FACID" INT,
    "APPT_TYPE" TEXT,
    FOREIGN KEY ("DNO") REFERENCES "DEPARTMENT"("DNO"),
    FOREIGN KEY ("FACID") REFERENCES "FACULTY"("FACID")
);
CREATE TABLE "COURSE" (
    "CID" TEXT,
    "DNO" INT,
    "INSTRUCTOR" INT,
    "CNAME" TEXT,
    "CREDITS" INT,
    "DAYS" TEXT,
    "HOURS" TEXT,
    PRIMARY KEY ("CID"),
    FOREIGN KEY ("DNO") REFERENCES "DEPARTMENT"("DNO"),
    FOREIGN KEY ("INSTRUCTOR") REFERENCES "FACULTY"("FACID")
);
CREATE TABLE "MINOR_IN" (
    "DNO" INT,
    "STUID" INT,
    FOREIGN KEY ("DNO") REFERENCES "DEPARTMENT"("DNO"),
    FOREIGN KEY ("STUID") REFERENCES "STUDENT"("STUID")
);
CREATE TABLE "ENROLLED_IN" (
    "GRADE" TEXT,
    "CID" TEXT,
    "STUID" INT,
    FOREIGN KEY ("GRADE") REFERENCES "GRADECONVERSION"("LETTERGRADE"),
    FOREIGN KEY ("CID") REFERENCES "COURSE"("CID"),
    FOREIGN KEY ("STUID") REFERENCES "STUDENT"("STUID")
);
CREATE TABLE "GRADECONVERSION" (
    "LETTERGRADE" TEXT,
    "GRADEPOINT" FLOAT,
    PRIMARY KEY ("LETTERGRADE")
);

