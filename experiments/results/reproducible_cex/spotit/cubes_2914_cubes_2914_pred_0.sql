-- Schema DDL
CREATE TABLE "CLASS" (
    "CLASS_CODE" TEXT,
    "PROF_NUM" INT,
    "CRS_CODE" TEXT,
    "CLASS_SECTION" TEXT,
    "CLASS_TIME" TEXT,
    "CLASS_ROOM" TEXT,
    PRIMARY KEY ("CLASS_CODE"),
    FOREIGN KEY ("PROF_NUM") REFERENCES "EMPLOYEE"("EMP_NUM"),
    FOREIGN KEY ("CRS_CODE") REFERENCES "COURSE"("CRS_CODE")
);
CREATE TABLE "COURSE" (
    "CRS_CODE" TEXT,
    "DEPT_CODE" TEXT,
    "CRS_DESCRIPTION" TEXT,
    "CRS_CREDIT" FLOAT,
    PRIMARY KEY ("CRS_CODE"),
    FOREIGN KEY ("DEPT_CODE") REFERENCES "DEPARTMENT"("DEPT_CODE")
);
CREATE TABLE "DEPARTMENT" (
    "DEPT_CODE" TEXT,
    "EMP_NUM" INT,
    "DEPT_NAME" TEXT,
    "SCHOOL_CODE" TEXT,
    "DEPT_ADDRESS" TEXT,
    "DEPT_EXTENSION" TEXT,
    PRIMARY KEY ("DEPT_CODE"),
    FOREIGN KEY ("EMP_NUM") REFERENCES "EMPLOYEE"("EMP_NUM")
);
CREATE TABLE "EMPLOYEE" (
    "EMP_NUM" INT,
    "EMP_LNAME" TEXT,
    "EMP_FNAME" TEXT,
    "EMP_INITIAL" TEXT,
    "EMP_JOBCODE" TEXT,
    "EMP_HIREDATE" DATETIME,
    "EMP_DOB" DATETIME,
    PRIMARY KEY ("EMP_NUM")
);
CREATE TABLE "ENROLL" (
    "STU_NUM" INT,
    "CLASS_CODE" TEXT,
    "ENROLL_GRADE" TEXT,
    FOREIGN KEY ("STU_NUM") REFERENCES "STUDENT"("STU_NUM"),
    FOREIGN KEY ("CLASS_CODE") REFERENCES "CLASS"("CLASS_CODE")
);
CREATE TABLE "PROFESSOR" (
    "DEPT_CODE" TEXT,
    "EMP_NUM" INT,
    "PROF_OFFICE" TEXT,
    "PROF_EXTENSION" TEXT,
    "PROF_HIGH_DEGREE" TEXT,
    FOREIGN KEY ("DEPT_CODE") REFERENCES "DEPARTMENT"("DEPT_CODE"),
    FOREIGN KEY ("EMP_NUM") REFERENCES "EMPLOYEE"("EMP_NUM")
);
CREATE TABLE "STUDENT" (
    "STU_NUM" INT,
    "DEPT_CODE" TEXT,
    "STU_LNAME" TEXT,
    "STU_FNAME" TEXT,
    "STU_INIT" TEXT,
    "STU_DOB" DATETIME,
    "STU_HRS" INT,
    "STU_CLASS" TEXT,
    "STU_GPA" FLOAT,
    "STU_TRANSFER" FLOAT,
    "STU_PHONE" TEXT,
    "PROF_NUM" INT,
    PRIMARY KEY ("STU_NUM"),
    FOREIGN KEY ("DEPT_CODE") REFERENCES "DEPARTMENT"("DEPT_CODE")
);

