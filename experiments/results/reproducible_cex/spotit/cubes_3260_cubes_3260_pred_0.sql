-- Schema DDL
CREATE TABLE "ADDRESSES" (
    "ADDRESS_ID" INT,
    "LINE_1" TEXT,
    "LINE_2" TEXT,
    "CITY" TEXT,
    "ZIP_POSTCODE" TEXT,
    "STATE_PROVINCE_COUNTY" TEXT,
    "COUNTRY" TEXT,
    PRIMARY KEY ("ADDRESS_ID")
);
CREATE TABLE "PEOPLE" (
    "PERSON_ID" INT,
    "FIRST_NAME" TEXT,
    "MIDDLE_NAME" TEXT,
    "LAST_NAME" TEXT,
    "CELL_MOBILE_NUMBER" TEXT,
    "EMAIL_ADDRESS" TEXT,
    "LOGIN_NAME" TEXT,
    "PASSWORD" TEXT,
    PRIMARY KEY ("PERSON_ID")
);
CREATE TABLE "STUDENTS" (
    "STUDENT_ID" INT,
    "STUDENT_DETAILS" TEXT,
    PRIMARY KEY ("STUDENT_ID"),
    FOREIGN KEY ("STUDENT_ID") REFERENCES "PEOPLE"("PERSON_ID")
);
CREATE TABLE "COURSES" (
    "COURSE_ID" TEXT,
    "COURSE_NAME" TEXT,
    "COURSE_DESCRIPTION" TEXT,
    "OTHER_DETAILS" TEXT,
    PRIMARY KEY ("COURSE_ID")
);
CREATE TABLE "PEOPLE_ADDRESSES" (
    "PERSON_ADDRESS_ID" INT,
    "ADDRESS_ID" INT,
    "PERSON_ID" INT,
    "DATE_FROM" DATETIME,
    "DATE_TO" DATETIME,
    PRIMARY KEY ("PERSON_ADDRESS_ID"),
    FOREIGN KEY ("ADDRESS_ID") REFERENCES "ADDRESSES"("ADDRESS_ID"),
    FOREIGN KEY ("PERSON_ID") REFERENCES "PEOPLE"("PERSON_ID")
);
CREATE TABLE "STUDENT_COURSE_REGISTRATIONS" (
    "STUDENT_ID" INT,
    "COURSE_ID" INT,
    "REGISTRATION_DATE" DATETIME,
    PRIMARY KEY ("STUDENT_ID", "COURSE_ID"),
    UNIQUE ("STUDENT_ID"),
    UNIQUE ("COURSE_ID"),
    FOREIGN KEY ("COURSE_ID") REFERENCES "COURSES"("COURSE_ID"),
    FOREIGN KEY ("STUDENT_ID") REFERENCES "STUDENTS"("STUDENT_ID")
);
CREATE TABLE "STUDENT_COURSE_ATTENDANCE" (
    "STUDENT_ID" INT,
    "COURSE_ID" INT,
    "DATE_OF_ATTENDANCE" DATETIME,
    PRIMARY KEY ("STUDENT_ID", "COURSE_ID"),
    FOREIGN KEY ("STUDENT_ID") REFERENCES "STUDENT_COURSE_REGISTRATIONS"("STUDENT_ID"),
    FOREIGN KEY ("COURSE_ID") REFERENCES "STUDENT_COURSE_REGISTRATIONS"("COURSE_ID")
);
CREATE TABLE "CANDIDATES" (
    "CANDIDATE_ID" INT,
    "CANDIDATE_DETAILS" TEXT,
    PRIMARY KEY ("CANDIDATE_ID"),
    FOREIGN KEY ("CANDIDATE_ID") REFERENCES "PEOPLE"("PERSON_ID")
);
CREATE TABLE "CANDIDATE_ASSESSMENTS" (
    "CANDIDATE_ID" INT,
    "QUALIFICATION" TEXT,
    "ASSESSMENT_DATE" DATETIME,
    "ASESSMENT_OUTCOME_CODE" TEXT,
    PRIMARY KEY ("CANDIDATE_ID", "QUALIFICATION"),
    FOREIGN KEY ("CANDIDATE_ID") REFERENCES "CANDIDATES"("CANDIDATE_ID")
);

