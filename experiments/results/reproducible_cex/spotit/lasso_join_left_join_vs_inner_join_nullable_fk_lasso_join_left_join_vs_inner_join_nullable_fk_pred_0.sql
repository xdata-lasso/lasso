-- Schema DDL
CREATE TABLE "CUSTOMERS" (
    "CUSTOMER_ID" INT,
    "CUSTOMER_NAME" TEXT,
    "EMAIL" TEXT,
    PRIMARY KEY ("CUSTOMER_ID")
);
CREATE TABLE "CONTACTS" (
    "USER_ID" INT,
    "CONTACT_EMAIL" TEXT,
    "CONTACT_NAME" TEXT,
    PRIMARY KEY ("USER_ID", "CONTACT_EMAIL"),
    FOREIGN KEY ("USER_ID") REFERENCES "CUSTOMERS"("CUSTOMER_ID")
);
CREATE TABLE "INVOICES" (
    "INVOICE_ID" INT,
    "USER_ID" INT,
    "PRICE" INT,
    PRIMARY KEY ("INVOICE_ID"),
    FOREIGN KEY ("USER_ID") REFERENCES "CUSTOMERS"("CUSTOMER_ID")
);

