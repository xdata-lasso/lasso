CREATE TABLE "STADIUM" (
    "ID" INT,
    "NAME" TEXT,
    "CAPACITY" INT,
    "CITY" TEXT,
    "COUNTRY" TEXT,
    "OPENING_YEAR" INT,
    PRIMARY KEY ("ID")
);
CREATE TABLE "EVENT" (
    "ID" INT,
    "STADIUM_ID" INT,
    "NAME" TEXT,
    "YEAR" TEXT,
    PRIMARY KEY ("ID"),
    FOREIGN KEY ("STADIUM_ID") REFERENCES "STADIUM"("ID")
);
CREATE TABLE "RECORD" (
    "SWIMMER_ID" INT,
    "EVENT_ID" INT,
    "ID" INT,
    "RESULT" TEXT,
    PRIMARY KEY ("SWIMMER_ID", "EVENT_ID"),
    FOREIGN KEY ("SWIMMER_ID") REFERENCES "SWIMMER"("ID"),
    FOREIGN KEY ("EVENT_ID") REFERENCES "EVENT"("ID")
);

