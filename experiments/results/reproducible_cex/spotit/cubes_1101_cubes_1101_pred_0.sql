    "NUM_EMPLOYEES" FLOAT,
    PRIMARY KEY ("DEPARTMENT_ID")
);
CREATE TABLE "HEAD" (
    "HEAD_ID" INT,
    "NAME" TEXT,
    "BORN_STATE" TEXT,
    "AGE" FLOAT,
    PRIMARY KEY ("HEAD_ID")
);
