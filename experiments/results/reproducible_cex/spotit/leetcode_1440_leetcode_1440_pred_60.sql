CREATE TABLE "VARIABLES" (
    "NAME" TEXT,
    "VALUE" INT,
    PRIMARY KEY ("NAME")
);
CREATE TABLE "EXPRESSIONS" (
    "LEFT_OPERAND" TEXT,
    "OPERATOR" TEXT,
    "RIGHT_OPERAND" TEXT,
    PRIMARY KEY ("LEFT_OPERAND", "OPERATOR", "RIGHT_OPERAND"),
    FOREIGN KEY ("LEFT_OPERAND") REFERENCES "VARIABLES"("NAME"),
    FOREIGN KEY ("RIGHT_OPERAND") REFERENCES "VARIABLES"("NAME")
);

