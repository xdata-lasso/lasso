-- Schema DDL
CREATE TABLE "CUSTOMERS" (
    "CUSTOMER_ID" INT,
    "CUSTOMER_DETAILS" TEXT,
    PRIMARY KEY ("CUSTOMER_ID")
);
CREATE TABLE "STAFF" (
    "STAFF_ID" INT,
    "STAFF_DETAILS" TEXT,
    PRIMARY KEY ("STAFF_ID")
);
CREATE TABLE "POLICIES" (
    "POLICY_ID" INT,
    "CUSTOMER_ID" INT,
    "POLICY_TYPE_CODE" TEXT,
    "START_DATE" DATETIME,
    "END_DATE" DATETIME,
    PRIMARY KEY ("POLICY_ID"),
    FOREIGN KEY ("CUSTOMER_ID") REFERENCES "CUSTOMERS"("CUSTOMER_ID")
);
CREATE TABLE "CLAIM_HEADERS" (
    "CLAIM_HEADER_ID" INT,
    "POLICY_ID" INT,
    "CLAIM_STATUS_CODE" TEXT,
    "CLAIM_TYPE_CODE" TEXT,
    "DATE_OF_CLAIM" DATETIME,
    "DATE_OF_SETTLEMENT" DATETIME,
    "AMOUNT_CLAIMED" FLOAT,
    "AMOUNT_PIAD" FLOAT,
    PRIMARY KEY ("CLAIM_HEADER_ID"),
    FOREIGN KEY ("POLICY_ID") REFERENCES "POLICIES"("POLICY_ID")
);
CREATE TABLE "CLAIMS_DOCUMENTS" (
    "CLAIM_ID" INT,
    "DOCUMENT_TYPE_CODE" TEXT,
    "CREATED_BY_STAFF_ID" INT,
    "CREATED_DATE" INT,
    PRIMARY KEY ("CLAIM_ID", "DOCUMENT_TYPE_CODE"),
    FOREIGN KEY ("CREATED_BY_STAFF_ID") REFERENCES "STAFF"("STAFF_ID"),
    FOREIGN KEY ("CLAIM_ID") REFERENCES "CLAIM_HEADERS"("CLAIM_HEADER_ID")
);
CREATE TABLE "CLAIMS_PROCESSING_STAGES" (
    "CLAIM_STAGE_ID" INT,
    "NEXT_CLAIM_STAGE_ID" INT,
    "CLAIM_STATUS_NAME" TEXT,
    "CLAIM_STATUS_DESCRIPTION" TEXT,
    PRIMARY KEY ("CLAIM_STAGE_ID")
);
CREATE TABLE "CLAIMS_PROCESSING" (
    "CLAIM_PROCESSING_ID" INT,
    "STAFF_ID" INT,
    "CLAIM_ID" INT,
    "CLAIM_OUTCOME_CODE" TEXT,
    "CLAIM_STAGE_ID" INT,
    PRIMARY KEY ("CLAIM_PROCESSING_ID"),
    FOREIGN KEY ("STAFF_ID") REFERENCES "STAFF"("STAFF_ID"),
    FOREIGN KEY ("CLAIM_ID") REFERENCES "CLAIM_HEADERS"("CLAIM_HEADER_ID")
);

