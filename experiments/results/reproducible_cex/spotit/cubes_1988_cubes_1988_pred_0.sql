    "CUSTOMER_ID" INT,
    "PAYMENT_METHOD_CODE" TEXT,
    "CUSTOMER_NUMBER" TEXT,
    "CUSTOMER_NAME" TEXT,
    "CUSTOMER_ADDRESS" TEXT,
