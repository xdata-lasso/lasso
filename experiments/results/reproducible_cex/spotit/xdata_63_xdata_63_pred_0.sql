CREATE TABLE "CLASSROOM" (
    "BUILDING" TEXT,
    "ROOM_NUMBER" TEXT,
    "CAPACITY" FLOAT,
    PRIMARY KEY ("BUILDING", "ROOM_NUMBER")
);
CREATE TABLE "DEPARTMENT" (
    "DEPT_NAME" TEXT,
    "BUILDING" TEXT,
    "BUDGET" FLOAT,
    PRIMARY KEY ("DEPT_NAME"),
    CHECK (budget > 0)
);
CREATE TABLE "COURSE" (
    "COURSE_ID" TEXT,
    "TITLE" TEXT,
    "DEPT_NAME" TEXT,
    "CREDITS" FLOAT,
    PRIMARY KEY ("COURSE_ID"),
    FOREIGN KEY ("DEPT_NAME") REFERENCES "DEPARTMENT"("DEPT_NAME"),
    CHECK (credits > 0)
);
CREATE TABLE "INSTRUCTOR" (
    "ID" TEXT,
    "NAME" TEXT NOT NULL,
    "DEPT_NAME" TEXT,
    "SALARY" FLOAT,
    PRIMARY KEY ("ID"),
    FOREIGN KEY ("DEPT_NAME") REFERENCES "DEPARTMENT"("DEPT_NAME"),
    CHECK (salary > 29000)
);
CREATE TABLE "SECTION" (
    "COURSE_ID" TEXT,
    "SEC_ID" TEXT,
    "SEMESTER" TEXT,
    "YEAR" FLOAT,
    "BUILDING" TEXT,
    "ROOM_NUMBER" TEXT,
    "TIME_SLOT_ID" TEXT,
    PRIMARY KEY ("COURSE_ID", "SEC_ID", "SEMESTER", "YEAR"),
    FOREIGN KEY ("COURSE_ID") REFERENCES "COURSE"("COURSE_ID"),
    FOREIGN KEY ("BUILDING") REFERENCES "CLASSROOM"("BUILDING"),
    CHECK (semester IN ('Fall', 'Winter', 'Spring', 'Summer')),
    CHECK (year > 1701 AND year < 2100)
);
CREATE TABLE "TEACHES" (
    "ID" TEXT,
    "COURSE_ID" TEXT,
    "SEC_ID" TEXT,
    "SEMESTER" TEXT,
    "YEAR" FLOAT,
    PRIMARY KEY ("ID", "COURSE_ID", "SEC_ID", "SEMESTER", "YEAR"),
    FOREIGN KEY ("COURSE_ID") REFERENCES "SECTION"("COURSE_ID"),
    FOREIGN KEY ("ID") REFERENCES "INSTRUCTOR"("ID")
);
CREATE TABLE "STUDENT" (
    "ID" TEXT,
    "NAME" TEXT NOT NULL,
    "DEPT_NAME" TEXT,
    "TOT_CRED" FLOAT,
    PRIMARY KEY ("ID"),
    FOREIGN KEY ("DEPT_NAME") REFERENCES "DEPARTMENT"("DEPT_NAME"),
    CHECK (tot_cred >= 0)
);
CREATE TABLE "TAKES" (
    "ID" TEXT,
    "COURSE_ID" TEXT,
    "SEC_ID" TEXT,
    "SEMESTER" TEXT,
    "YEAR" FLOAT,
    "GRADE" TEXT,
    PRIMARY KEY ("ID", "COURSE_ID", "SEC_ID", "SEMESTER", "YEAR"),
    FOREIGN KEY ("COURSE_ID") REFERENCES "SECTION"("COURSE_ID"),
    FOREIGN KEY ("ID") REFERENCES "STUDENT"("ID")
);
CREATE TABLE "ADVISOR" (
    "S_ID" TEXT,
    "I_ID" TEXT,
    PRIMARY KEY ("S_ID"),
    FOREIGN KEY ("I_ID") REFERENCES "INSTRUCTOR"("ID"),
    FOREIGN KEY ("S_ID") REFERENCES "STUDENT"("ID")
);
CREATE TABLE "TIME_SLOT" (
    "TIME_SLOT_ID" TEXT,
    "DAY" TEXT,
    "START_HR" FLOAT,
    "START_MIN" FLOAT,
    "END_HR" FLOAT,
    "END_MIN" FLOAT,
    PRIMARY KEY ("TIME_SLOT_ID", "DAY", "START_HR", "START_MIN"),
    CHECK (start_hr >= 0 AND start_hr < 24),
    CHECK (start_min >= 0 AND start_min < 60),
    CHECK (end_hr >= 0 AND end_hr < 24),
    CHECK (end_min >= 0 AND end_min < 60)
);
CREATE TABLE "PREREQ" (
    "COURSE_ID" TEXT,
    "PREREQ_ID" TEXT,
    PRIMARY KEY ("COURSE_ID", "PREREQ_ID"),
    FOREIGN KEY ("COURSE_ID") REFERENCES "COURSE"("COURSE_ID"),
    FOREIGN KEY ("PREREQ_ID") REFERENCES "COURSE"("COURSE_ID")
);
CREATE TABLE "GRADE_VALUE" (
    "GRADE" TEXT,
    "VALUE" FLOAT,
    PRIMARY KEY ("GRADE")
);

