-- Schema DDL
CREATE TABLE "ADDRESSES" (
    "ADDRESS_ID" INT,
    "LINE_1_NUMBER_BUILDING" TEXT,
    "CITY" TEXT,
    "ZIP_POSTCODE" TEXT,
    "STATE_PROVINCE_COUNTY" TEXT,
    "COUNTRY" TEXT,
    PRIMARY KEY ("ADDRESS_ID")
);
CREATE TABLE "STAFF" (
    "STAFF_ID" INT,
    "STAFF_ADDRESS_ID" INT,
    "NICKNAME" TEXT,
    "FIRST_NAME" TEXT,
    "MIDDLE_NAME" TEXT,
    "LAST_NAME" TEXT,
    "DATE_OF_BIRTH" DATETIME,
    "DATE_JOINED_STAFF" DATETIME,
    "DATE_LEFT_STAFF" DATETIME,
    PRIMARY KEY ("STAFF_ID"),
    FOREIGN KEY ("STAFF_ADDRESS_ID") REFERENCES "ADDRESSES"("ADDRESS_ID")
);
CREATE TABLE "VEHICLES" (
    "VEHICLE_ID" INT,
    "VEHICLE_DETAILS" TEXT,
    PRIMARY KEY ("VEHICLE_ID")
);
CREATE TABLE "CUSTOMERS" (
    "CUSTOMER_ID" INT,
    "CUSTOMER_ADDRESS_ID" INT,
    "CUSTOMER_STATUS_CODE" TEXT,
    "DATE_BECAME_CUSTOMER" DATETIME,
    "DATE_OF_BIRTH" DATETIME,
    "FIRST_NAME" TEXT,
    "LAST_NAME" TEXT,
    "AMOUNT_OUTSTANDING" FLOAT,
    "EMAIL_ADDRESS" TEXT,
    "PHONE_NUMBER" TEXT,
    "CELL_MOBILE_PHONE_NUMBER" TEXT,
    PRIMARY KEY ("CUSTOMER_ID"),
    FOREIGN KEY ("CUSTOMER_ADDRESS_ID") REFERENCES "ADDRESSES"("ADDRESS_ID")
);
CREATE TABLE "CUSTOMER_PAYMENTS" (
    "CUSTOMER_ID" INT,
    "DATETIME_PAYMENT" DATETIME,
    "PAYMENT_METHOD_CODE" TEXT,
    "AMOUNT_PAYMENT" FLOAT,
    PRIMARY KEY ("CUSTOMER_ID", "DATETIME_PAYMENT"),
    FOREIGN KEY ("CUSTOMER_ID") REFERENCES "CUSTOMERS"("CUSTOMER_ID")
);
CREATE TABLE "LESSONS" (
    "LESSON_ID" INT,
    "CUSTOMER_ID" INT,
    "STAFF_ID" INT,
    "VEHICLE_ID" INT,
    "LESSON_STATUS_CODE" TEXT,
    "LESSON_DATE" DATETIME,
    "LESSON_TIME" TEXT,
    "PRICE" FLOAT,
    PRIMARY KEY ("LESSON_ID"),
    FOREIGN KEY ("CUSTOMER_ID") REFERENCES "CUSTOMERS"("CUSTOMER_ID"),
    FOREIGN KEY ("STAFF_ID") REFERENCES "STAFF"("STAFF_ID"),
    FOREIGN KEY ("VEHICLE_ID") REFERENCES "VEHICLES"("VEHICLE_ID")
);

