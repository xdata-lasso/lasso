    "PLAYER_ID" INT,
    "COACH_ID" INT,
    "STARTING_YEAR" INT,
    PRIMARY KEY ("PLAYER_ID", "COACH_ID"),
    FOREIGN KEY ("COACH_ID") REFERENCES "COACH"("COACH_ID"),
    FOREIGN KEY ("PLAYER_ID") REFERENCES "PLAYER"("PLAYER_ID")
);
