    "COACH_ID" INT,
    "CLUB_ID" INT,
    "COACH_NAME" TEXT,
    "GENDER" TEXT,
    "RANK" INT,
    PRIMARY KEY ("COACH_ID"),
    FOREIGN KEY ("CLUB_ID") REFERENCES "CLUB"("CLUB_ID")
);
