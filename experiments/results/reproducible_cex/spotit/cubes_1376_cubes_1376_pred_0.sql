);
CREATE TABLE "MATCH_SEASON" (
    "SEASON" FLOAT,
    "TEAM" INT,
    "COUNTRY" INT,
    "PLAYER" TEXT,
    "POSITION" TEXT,
    "DRAFT_PICK_NUMBER" INT,
    "DRAFT_CLASS" TEXT,
    "COLLEGE" TEXT,
    PRIMARY KEY ("SEASON"),
    FOREIGN KEY ("TEAM") REFERENCES "TEAM"("TEAM_ID"),
    FOREIGN KEY ("COUNTRY") REFERENCES "COUNTRY"("COUNTRY_ID")
);
CREATE TABLE "PLAYER" (
    "PLAYER_ID" INT,
    "TEAM" INT,
    "PLAYER" TEXT,
