    PRIMARY KEY ("FARM_ID")
);
CREATE TABLE "FARM_COMPETITION" (
    "COMPETITION_ID" INT,
    "HOST_CITY_ID" INT,
    "YEAR" INT,
    "THEME" TEXT,
    "HOSTS" TEXT,
    PRIMARY KEY ("COMPETITION_ID"),
    FOREIGN KEY ("HOST_CITY_ID") REFERENCES "CITY"("CITY_ID")
);
