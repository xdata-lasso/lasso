    "COMPETITION_ID" INT,
    "FARM_ID" INT,
    "RANK" INT,
    PRIMARY KEY ("COMPETITION_ID", "FARM_ID"),
    FOREIGN KEY ("FARM_ID") REFERENCES "FARM"("FARM_ID"),
    FOREIGN KEY ("COMPETITION_ID") REFERENCES "FARM_COMPETITION"("COMPETITION_ID")
);

