);
CREATE TABLE "EVENTS" (
    "EVENT_ID" INT,
    "SERVICE_ID" INT,
    "EVENT_DETAILS" TEXT,
    PRIMARY KEY ("EVENT_ID"),
    FOREIGN KEY ("SERVICE_ID") REFERENCES "SERVICES"("SERVICE_ID")
);
