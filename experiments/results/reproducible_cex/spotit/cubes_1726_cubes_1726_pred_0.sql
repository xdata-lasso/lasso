-- Schema DDL
CREATE TABLE "CAMPUSES" (
    "ID" INT,
    "CAMPUS" TEXT,
    "LOCATION" TEXT,
    "COUNTY" TEXT,
    "YEAR" INT,
    PRIMARY KEY ("ID")
);
CREATE TABLE "CSU_FEES" (
    "CAMPUS" INT,
    "YEAR" INT,
    "CAMPUSFEE" INT,
    PRIMARY KEY ("CAMPUS"),
    FOREIGN KEY ("CAMPUS") REFERENCES "CAMPUSES"("ID")
);
CREATE TABLE "DEGREES" (
    "YEAR" INT,
    "CAMPUS" INT,
    "DEGREES" INT,
    PRIMARY KEY ("YEAR", "CAMPUS"),
    FOREIGN KEY ("CAMPUS") REFERENCES "CAMPUSES"("ID")
);
CREATE TABLE "DISCIPLINE_ENROLLMENTS" (
    "CAMPUS" INT,
    "DISCIPLINE" INT,
    "YEAR" INT,
    "UNDERGRADUATE" INT,
    "GRADUATE" INT,
    PRIMARY KEY ("CAMPUS", "DISCIPLINE"),
    FOREIGN KEY ("CAMPUS") REFERENCES "CAMPUSES"("ID")
);
CREATE TABLE "ENROLLMENTS" (
    "CAMPUS" INT,
    "YEAR" INT,
    "TOTALENROLLMENT_AY" INT,
    "FTE_AY" INT,
    PRIMARY KEY ("CAMPUS", "YEAR"),
    FOREIGN KEY ("CAMPUS") REFERENCES "CAMPUSES"("ID")
);
CREATE TABLE "FACULTY" (
    "CAMPUS" INT,
    "YEAR" INT,
    "FACULTY" FLOAT,
    FOREIGN KEY ("CAMPUS") REFERENCES "CAMPUSES"("ID")
);

