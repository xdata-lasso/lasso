    FOREIGN KEY ("LINK_TO_MEMBER") REFERENCES "MEMBER"("MEMBER_ID")
);
CREATE TABLE "INCOME" (
    "INCOME_ID" TEXT,
    "DATE_RECEIVED" TEXT,
    "AMOUNT" INT,
