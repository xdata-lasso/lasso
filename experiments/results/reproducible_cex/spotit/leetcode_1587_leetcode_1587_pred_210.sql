CREATE TABLE "USERS" (
    "ACCOUNT" INT,
    "NAME" TEXT,
    PRIMARY KEY ("ACCOUNT"),
    UNIQUE ("NAME")
);
CREATE TABLE "TRANSACTIONS" (
    "TRANS_ID" INT,
    "ACCOUNT" INT,
    "AMOUNT" INT,
    "TRANSACTED_ON" DATE,
    PRIMARY KEY ("TRANS_ID"),
    FOREIGN KEY ("ACCOUNT") REFERENCES "USERS"("ACCOUNT")
);

