    "LOCATION" TEXT,
    "STATUS" TEXT,
    PRIMARY KEY ("EVENT_ID")
);
CREATE TABLE "MAJOR" (
    "MAJOR_ID" TEXT,
    "MAJOR_NAME" TEXT,
    "DEPARTMENT" TEXT,
    "COLLEGE" TEXT,
    PRIMARY KEY ("MAJOR_ID")
);
