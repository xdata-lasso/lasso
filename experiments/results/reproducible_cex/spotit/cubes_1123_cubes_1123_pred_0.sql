CREATE TABLE "GENRE" (
    "G_NAME" TEXT,
    "RATING" TEXT,
    "MOST_POPULAR_IN" TEXT,
    PRIMARY KEY ("G_NAME")
);
CREATE TABLE "ARTIST" (
    "ARTIST_NAME" TEXT,
    "PREFERRED_GENRE" TEXT,
    "COUNTRY" TEXT,
    "GENDER" TEXT,
    PRIMARY KEY ("ARTIST_NAME"),
    FOREIGN KEY ("PREFERRED_GENRE") REFERENCES "GENRE"("G_NAME")
);
CREATE TABLE "FILES" (
    "F_ID" FLOAT,
    "ARTIST_NAME" TEXT,
    "FILE_SIZE" TEXT,
    "DURATION" TEXT,
    "FORMATS" TEXT,
    PRIMARY KEY ("F_ID"),
    FOREIGN KEY ("ARTIST_NAME") REFERENCES "ARTIST"("ARTIST_NAME")
);
CREATE TABLE "SONG" (
    "SONG_NAME" TEXT,
    "GENRE_IS" TEXT,
    "F_ID" FLOAT,
    "ARTIST_NAME" TEXT,
    "COUNTRY" TEXT,
    "RATING" FLOAT,
    "LANGUAGES" TEXT,
    "RELEASEDATE" DATE,
    "RESOLUTION" FLOAT,
    PRIMARY KEY ("SONG_NAME"),
    FOREIGN KEY ("GENRE_IS") REFERENCES "GENRE"("G_NAME"),
    FOREIGN KEY ("F_ID") REFERENCES "FILES"("F_ID"),
    FOREIGN KEY ("ARTIST_NAME") REFERENCES "ARTIST"("ARTIST_NAME")
);

